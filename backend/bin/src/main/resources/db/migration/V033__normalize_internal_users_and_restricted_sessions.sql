-- Normaliza usuarios internos, conserva datos existentes y agrega trazabilidad de estados.

ALTER TABLE APP_USER ADD (
    STATUS_REASON VARCHAR2(500 CHAR),
    STATUS_CHANGED_AT TIMESTAMP WITH TIME ZONE,
    STATUS_CHANGED_BY NUMBER
);

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE APP_USER DROP CONSTRAINT CK_APP_USER_STATUS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2443 THEN RAISE; END IF;
END;
/

UPDATE APP_USER
SET STATUS = CASE STATUS
    WHEN 'PENDING' THEN 'INACTIVE'
    WHEN 'DISABLED' THEN 'INACTIVE'
    WHEN 'LOCKED' THEN 'ACTIVE'
    ELSE STATUS
END;

UPDATE APP_USER u
SET u.STATUS = 'INACTIVE',
    u.STATUS_REASON = 'Rol legado USER desactivado durante la separación de estudiantes',
    u.STATUS_CHANGED_AT = SYSTIMESTAMP
WHERE EXISTS (
    SELECT 1
    FROM APP_USER_ROLE ur
    JOIN APP_ROLE r ON r.ROLE_ID = ur.ROLE_ID
    WHERE ur.USER_ID = u.USER_ID
      AND r.ROLE_CODE = 'USER'
)
AND NOT EXISTS (
    SELECT 1
    FROM APP_USER_ROLE ur
    JOIN APP_ROLE r ON r.ROLE_ID = ur.ROLE_ID
    WHERE ur.USER_ID = u.USER_ID
      AND r.ROLE_CODE IN ('ADMINISTRATOR', 'MANAGER', 'SUPERVISOR')
);

UPDATE APP_USER
SET STATUS_REASON = COALESCE(STATUS_REASON, 'Estado migrado al modelo definitivo de usuarios internos'),
    STATUS_CHANGED_AT = COALESCE(STATUS_CHANGED_AT, UPDATED_AT, CREATED_AT, SYSTIMESTAMP)
WHERE STATUS_REASON IS NULL OR STATUS_CHANGED_AT IS NULL;

ALTER TABLE APP_USER ADD CONSTRAINT CK_APP_USER_STATUS
    CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DELETED'));

ALTER TABLE APP_USER ADD CONSTRAINT FK_APP_USER_STATUS_CHANGED_BY
    FOREIGN KEY (STATUS_CHANGED_BY) REFERENCES APP_USER (USER_ID);

CREATE TABLE INTERNAL_USER_STATUS_HISTORY (
    STATUS_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    ACTOR_USER_ID NUMBER,
    PREVIOUS_STATUS VARCHAR2(30 CHAR),
    NEW_STATUS VARCHAR2(30 CHAR) NOT NULL,
    REASON VARCHAR2(500 CHAR),
    OCCURRED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INTERNAL_USER_STATUS_HISTORY PRIMARY KEY (STATUS_HISTORY_ID),
    CONSTRAINT FK_IUSH_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_IUSH_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_IUSH_PREVIOUS_STATUS CHECK (
        PREVIOUS_STATUS IS NULL OR PREVIOUS_STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DELETED')
    ),
    CONSTRAINT CK_IUSH_NEW_STATUS CHECK (
        NEW_STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DELETED')
    )
);

CREATE INDEX IX_IUSH_USER_DATE
    ON INTERNAL_USER_STATUS_HISTORY (USER_ID, OCCURRED_AT DESC);

INSERT INTO INTERNAL_USER_STATUS_HISTORY (
    USER_ID, ACTOR_USER_ID, PREVIOUS_STATUS, NEW_STATUS, REASON, OCCURRED_AT
)
SELECT USER_ID, STATUS_CHANGED_BY, NULL, STATUS, STATUS_REASON, STATUS_CHANGED_AT
FROM APP_USER;

ALTER TABLE AUTH_SESSION ADD (
    SESSION_SCOPE VARCHAR2(30 CHAR) DEFAULT 'FULL' NOT NULL
);

ALTER TABLE AUTH_SESSION ADD CONSTRAINT CK_AUTH_SESSION_SCOPE
    CHECK (SESSION_SCOPE IN ('FULL', 'PASSWORD_CHANGE'));

UPDATE APP_ROLE
SET STATUS = 'INACTIVE'
WHERE ROLE_CODE = 'USER';

-- Conserva el rol legado para trazabilidad, pero deja de otorgar acceso operativo.
DELETE FROM APP_ROLE_PERMISSION
WHERE ROLE_ID = (SELECT ROLE_ID FROM APP_ROLE WHERE ROLE_CODE = 'USER');

-- Los roles internos organizacionales requieren los permisos base de autenticación y perfil.
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM APP_ROLE r
CROSS JOIN APP_PERMISSION p
WHERE r.ROLE_CODE IN ('MANAGER', 'SUPERVISOR')
  AND p.PERMISSION_CODE IN ('DASHBOARD_VIEW', 'USER_PANEL_VIEW', 'PROFILE_VIEW', 'PASSWORD_CHANGE')
  AND NOT EXISTS (
      SELECT 1
      FROM APP_ROLE_PERMISSION rp
      WHERE rp.ROLE_ID = r.ROLE_ID
        AND rp.PERMISSION_ID = p.PERMISSION_ID
  );
