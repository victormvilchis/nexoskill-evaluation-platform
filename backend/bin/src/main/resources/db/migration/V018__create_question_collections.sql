CREATE TABLE QUESTION_COLLECTION (
    COLLECTION_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID           VARCHAR2(36 CHAR) NOT NULL,
    COLLECTION_NAME     VARCHAR2(180 CHAR) NOT NULL,
    NORMALIZED_NAME     VARCHAR2(180 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(1000 CHAR),
    STATUS              VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY          NUMBER NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY          NUMBER,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE,
    VERSION_NO          NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_QUESTION_COLLECTION PRIMARY KEY (COLLECTION_ID),
    CONSTRAINT UK_QUESTION_COLLECTION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_QUESTION_COLLECTION_NAME UNIQUE (NORMALIZED_NAME),
    CONSTRAINT FK_QUESTION_COLLECTION_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_QUESTION_COLLECTION_UPDATER FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_QUESTION_COLLECTION_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE COLLECTION_CATEGORY_RELATION (
    COLLECTION_ID NUMBER NOT NULL,
    CATEGORY_ID   NUMBER NOT NULL,
    ADDED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_COLLECTION_CATEGORY_REL PRIMARY KEY (COLLECTION_ID, CATEGORY_ID),
    CONSTRAINT FK_CCR_COLLECTION FOREIGN KEY (COLLECTION_ID) REFERENCES QUESTION_COLLECTION (COLLECTION_ID),
    CONSTRAINT FK_CCR_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES QUESTION_CATEGORY (CATEGORY_ID)
);

CREATE TABLE COLLECTION_QUESTION_RELATION (
    COLLECTION_ID NUMBER NOT NULL,
    QUESTION_ID   NUMBER NOT NULL,
    ADDED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_COLLECTION_QUESTION_REL PRIMARY KEY (COLLECTION_ID, QUESTION_ID),
    CONSTRAINT FK_CQR_COLLECTION FOREIGN KEY (COLLECTION_ID) REFERENCES QUESTION_COLLECTION (COLLECTION_ID),
    CONSTRAINT FK_CQR_QUESTION FOREIGN KEY (QUESTION_ID) REFERENCES QUESTION (QUESTION_ID)
);

CREATE INDEX IX_COLLECTION_STATUS_NAME ON QUESTION_COLLECTION (STATUS, COLLECTION_NAME);
CREATE INDEX IX_CCR_CATEGORY ON COLLECTION_CATEGORY_RELATION (CATEGORY_ID, COLLECTION_ID);
CREATE INDEX IX_CQR_QUESTION ON COLLECTION_QUESTION_RELATION (QUESTION_ID, COLLECTION_ID);
