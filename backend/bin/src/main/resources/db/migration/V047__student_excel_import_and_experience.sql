DECLARE
    FUNCTION index_with_columns(p_table VARCHAR2, p_columns VARCHAR2) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM (
              SELECT i.INDEX_NAME,
                     LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION) COLUMN_LIST
                FROM USER_INDEXES i
                JOIN USER_IND_COLUMNS c ON c.INDEX_NAME = i.INDEX_NAME
               WHERE i.TABLE_NAME = UPPER(p_table)
               GROUP BY i.INDEX_NAME
          )
         WHERE COLUMN_LIST = UPPER(p_columns);
        RETURN v_count;
    END;
BEGIN
    IF index_with_columns('STUDENT_EXPERIENCE_ITEM', 'ORGANIZATION_ID,STUDENT_ID,ITEM_TYPE') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_EXP_ORG_STUDENT ON STUDENT_EXPERIENCE_ITEM (ORGANIZATION_ID, STUDENT_ID, ITEM_TYPE)';
    END IF;

    IF index_with_columns('STUDENT_IMPORT_RECEIPT', 'ORGANIZATION_ID,APPLIED_AT') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STU_IMPORT_RECEIPT_DATE ON STUDENT_IMPORT_RECEIPT (ORGANIZATION_ID, APPLIED_AT)';
    END IF;
END;
