DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'STUDENT_EXPERIENCE_ITEM';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STUDENT_EXPERIENCE_ITEM (
                STUDENT_EXPERIENCE_ITEM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
                PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
                STUDENT_ID NUMBER NOT NULL,
                ORGANIZATION_ID NUMBER NOT NULL,
                ITEM_TYPE VARCHAR2(40 CHAR) NOT NULL,
                ITEM_NAME VARCHAR2(200 CHAR) NOT NULL,
                NORMALIZED_NAME VARCHAR2(200 CHAR) NOT NULL,
                LEVEL_CODE VARCHAR2(10 CHAR),
                DISPLAY_ORDER NUMBER DEFAULT 0 NOT NULL,
                CREATED_BY NUMBER NOT NULL,
                UPDATED_BY NUMBER NOT NULL,
                CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                VERSION_NO NUMBER DEFAULT 0 NOT NULL,
                CONSTRAINT PK_STUDENT_EXPERIENCE PRIMARY KEY (STUDENT_EXPERIENCE_ITEM_ID),
                CONSTRAINT UK_STUDENT_EXP_PUBLIC UNIQUE (PUBLIC_ID),
                CONSTRAINT UK_STUDENT_EXP_ITEM UNIQUE (STUDENT_ID, ITEM_TYPE, NORMALIZED_NAME),
                CONSTRAINT FK_STUDENT_EXP_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (STUDENT_ID),
                CONSTRAINT FK_STUDENT_EXP_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
                CONSTRAINT FK_STUDENT_EXP_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
                CONSTRAINT FK_STUDENT_EXP_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID),
                CONSTRAINT CK_STUDENT_EXP_TYPE CHECK (ITEM_TYPE IN ('CURRENT_TECHNOLOGY','LANGUAGE','KNOWN_TECHNOLOGY')),
                CONSTRAINT CK_STUDENT_EXP_LEVEL CHECK (LEVEL_CODE IS NULL OR LEVEL_CODE IN ('JR','STD','SR')),
                CONSTRAINT CK_STUDENT_EXP_ORDER CHECK (DISPLAY_ORDER >= 0)
            )
        ]';
    ELSE
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'STUDENT_EXPERIENCE_ITEM'
           AND COLUMN_NAME IN ('STUDENT_EXPERIENCE_ITEM_ID','PUBLIC_ID','STUDENT_ID','ORGANIZATION_ID',
                               'ITEM_TYPE','ITEM_NAME','NORMALIZED_NAME','LEVEL_CODE','DISPLAY_ORDER',
                               'CREATED_BY','UPDATED_BY','CREATED_AT','UPDATED_AT','VERSION_NO');
        IF v_count <> 14 THEN
            RAISE_APPLICATION_ERROR(-20047,
                'STUDENT_EXPERIENCE_ITEM existe parcialmente. Revisa sus columnas antes de reintentar V047.');
        END IF;
    END IF;
END;
