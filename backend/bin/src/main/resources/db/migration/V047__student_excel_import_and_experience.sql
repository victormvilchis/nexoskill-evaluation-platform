DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'STUDENT_IMPORT_RECEIPT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STUDENT_IMPORT_RECEIPT (
                STUDENT_IMPORT_RECEIPT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
                PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
                ORGANIZATION_ID NUMBER NOT NULL,
                FILE_SHA256 VARCHAR2(64 CHAR) NOT NULL,
                TOTAL_ROWS NUMBER NOT NULL,
                CREATED_COUNT NUMBER DEFAULT 0 NOT NULL,
                UPDATED_COUNT NUMBER DEFAULT 0 NOT NULL,
                DEACTIVATED_COUNT NUMBER DEFAULT 0 NOT NULL,
                ERROR_COUNT NUMBER DEFAULT 0 NOT NULL,
                STATUS_CODE VARCHAR2(20 CHAR) DEFAULT 'PROCESSING' NOT NULL,
                APPLIED_BY NUMBER NOT NULL,
                APPLIED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                COMPLETED_AT TIMESTAMP WITH TIME ZONE,
                CONSTRAINT PK_STUDENT_IMPORT_RECEIPT PRIMARY KEY (STUDENT_IMPORT_RECEIPT_ID),
                CONSTRAINT UK_STU_IMPORT_RECEIPT_PUBLIC UNIQUE (PUBLIC_ID),
                CONSTRAINT UK_STU_IMPORT_RECEIPT_FILE UNIQUE (ORGANIZATION_ID, FILE_SHA256),
                CONSTRAINT FK_STU_IMPORT_RECEIPT_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
                CONSTRAINT FK_STU_IMPORT_RECEIPT_ACTOR FOREIGN KEY (APPLIED_BY) REFERENCES APP_USER (USER_ID),
                CONSTRAINT CK_STU_IMPORT_RECEIPT_STATUS CHECK (STATUS_CODE IN ('PROCESSING','COMPLETED')),
                CONSTRAINT CK_STU_IMPORT_RECEIPT_NUM CHECK (
                    TOTAL_ROWS >= 0 AND CREATED_COUNT >= 0 AND UPDATED_COUNT >= 0
                    AND DEACTIVATED_COUNT >= 0 AND ERROR_COUNT >= 0)
            )
        ]';
    ELSE
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'STUDENT_IMPORT_RECEIPT'
           AND COLUMN_NAME IN ('STUDENT_IMPORT_RECEIPT_ID','PUBLIC_ID','ORGANIZATION_ID','FILE_SHA256',
                               'TOTAL_ROWS','CREATED_COUNT','UPDATED_COUNT','DEACTIVATED_COUNT',
                               'ERROR_COUNT','STATUS_CODE','APPLIED_BY','APPLIED_AT','COMPLETED_AT');
        IF v_count <> 13 THEN
            RAISE_APPLICATION_ERROR(-20048,
                'STUDENT_IMPORT_RECEIPT existe parcialmente. Revisa sus columnas antes de reintentar V047.');
        END IF;
    END IF;
END;
