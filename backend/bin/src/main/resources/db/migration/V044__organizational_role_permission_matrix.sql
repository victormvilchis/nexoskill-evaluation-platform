-- Matriz definitiva de permisos organizacionales.
-- Gestor: lectura en Catálogos/Banco de Preguntas y administración completa de Estudiantes.
-- Supervisor: CRUD organizacional en Catálogos/Banco de Preguntas y administración completa de Estudiantes.

-- Retira permisos de escritura y gobierno global de Gestor y Supervisor antes de reconstruir la matriz.
DELETE FROM APP_ROLE_PERMISSION rp
 WHERE rp.ROLE_ID IN (
       SELECT r.ROLE_ID FROM APP_ROLE r WHERE r.ROLE_CODE IN ('MANAGER', 'SUPERVISOR')
   )
   AND rp.PERMISSION_ID IN (
       SELECT p.PERMISSION_ID
         FROM APP_PERMISSION p
        WHERE p.PERMISSION_CODE IN (
            'CATALOG_MANAGE',
            'QUESTION_CREATE', 'QUESTION_UPDATE', 'QUESTION_ARCHIVE',
            'QUESTION_CATEGORY_MANAGE', 'QUESTION_DUPLICATE', 'QUESTION_MEDIA_MANAGE',
            'FORM_CREATE', 'FORM_UPDATE', 'FORM_STATUS_CHANGE',
            'COLLECTION_MANAGE',
            'GLOBAL_CONTENT_PROMOTE', 'GLOBAL_CONTENT_VERSION_MANAGE',
            'GLOBAL_CONTENT_DISTRIBUTE', 'GLOBAL_CONTENT_SYNCHRONIZE',
            'TENANT_CONTEXT_SELECT',
            'ORGANIZATION_CREATE', 'ORGANIZATION_UPDATE', 'ORGANIZATION_STATUS_CHANGE',
            'ORGANIZATION_LICENSE_UPDATE'
        )
   );

-- Lectura compartida para Gestor y Supervisor.
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
  FROM APP_ROLE r
 CROSS JOIN APP_PERMISSION p
 WHERE r.ROLE_CODE IN ('MANAGER', 'SUPERVISOR')
   AND p.PERMISSION_CODE IN (
       'CATALOG_VIEW',
       'QUESTION_VIEW',
       'FORM_VIEW', 'FORM_PREVIEW',
       'COLLECTION_VIEW',
       'STUDENT_VIEW', 'STUDENT_CREATE', 'STUDENT_UPDATE',
       'STUDENT_STATUS_CHANGE', 'STUDENT_PASSWORD_RESET',
       'STUDENT_SESSION_MANAGE', 'STUDENT_DELETE',
       'STUDENT_CERTIFICATION_MANAGE', 'STUDENT_CERTIFICATION_CATALOG_VIEW'
   )
   AND NOT EXISTS (
       SELECT 1
         FROM APP_ROLE_PERMISSION current_value
        WHERE current_value.ROLE_ID = r.ROLE_ID
          AND current_value.PERMISSION_ID = p.PERMISSION_ID
   );

-- Escritura organizacional exclusiva del Supervisor.
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
  FROM APP_ROLE r
 CROSS JOIN APP_PERMISSION p
 WHERE r.ROLE_CODE = 'SUPERVISOR'
   AND p.PERMISSION_CODE IN (
       'CATALOG_MANAGE',
       'QUESTION_CREATE', 'QUESTION_UPDATE', 'QUESTION_ARCHIVE',
       'QUESTION_CATEGORY_MANAGE', 'QUESTION_DUPLICATE', 'QUESTION_MEDIA_MANAGE',
       'FORM_CREATE', 'FORM_UPDATE', 'FORM_STATUS_CHANGE',
       'COLLECTION_MANAGE'
   )
   AND NOT EXISTS (
       SELECT 1
         FROM APP_ROLE_PERMISSION current_value
        WHERE current_value.ROLE_ID = r.ROLE_ID
          AND current_value.PERMISSION_ID = p.PERMISSION_ID
   );

-- El Administrador global conserva gobierno transversal de contenido y estudiantes,
-- pero no gestión operativa de certificaciones.
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
  FROM APP_ROLE r
 CROSS JOIN APP_PERMISSION p
 WHERE r.ROLE_CODE = 'ADMINISTRATOR'
   AND p.PERMISSION_CODE IN (
       'CATALOG_VIEW', 'CATALOG_MANAGE',
       'QUESTION_VIEW', 'QUESTION_CREATE', 'QUESTION_UPDATE', 'QUESTION_ARCHIVE',
       'QUESTION_CATEGORY_MANAGE', 'QUESTION_DUPLICATE', 'QUESTION_MEDIA_MANAGE',
       'FORM_VIEW', 'FORM_CREATE', 'FORM_UPDATE', 'FORM_STATUS_CHANGE', 'FORM_PREVIEW',
       'COLLECTION_VIEW', 'COLLECTION_MANAGE',
       'STUDENT_VIEW', 'STUDENT_CREATE', 'STUDENT_UPDATE',
       'STUDENT_STATUS_CHANGE', 'STUDENT_PASSWORD_RESET',
       'STUDENT_SESSION_MANAGE', 'STUDENT_DELETE'
   )
   AND NOT EXISTS (
       SELECT 1
         FROM APP_ROLE_PERMISSION current_value
        WHERE current_value.ROLE_ID = r.ROLE_ID
          AND current_value.PERMISSION_ID = p.PERMISSION_ID
   );

DELETE FROM APP_ROLE_PERMISSION rp
 WHERE rp.ROLE_ID IN (
       SELECT r.ROLE_ID FROM APP_ROLE r WHERE r.ROLE_CODE = 'ADMINISTRATOR'
   )
   AND rp.PERMISSION_ID IN (
       SELECT p.PERMISSION_ID
         FROM APP_PERMISSION p
        WHERE p.PERMISSION_CODE IN ('STUDENT_CERTIFICATION_MANAGE', 'STUDENT_CERTIFICATION_CATALOG_VIEW')
   );


-- Fuerza la recarga de permisos efectivos en las sesiones existentes.
UPDATE AUTH_SESSION
   SET STATUS = 'REVOKED',
       REVOKED_AT = SYSTIMESTAMP
 WHERE STATUS = 'ACTIVE'
   AND EXISTS (
       SELECT 1
         FROM APP_USER_ROLE user_role
         JOIN APP_ROLE role_value ON role_value.ROLE_ID = user_role.ROLE_ID
        WHERE user_role.USER_ID = AUTH_SESSION.USER_ID
          AND role_value.ROLE_CODE IN ('ADMINISTRATOR', 'MANAGER', 'SUPERVISOR')
   );

COMMIT;
