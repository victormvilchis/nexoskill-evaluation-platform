DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'QUESTION' AND CONSTRAINT_NAME = 'CK_QUESTION_STATUS';
    IF v_count > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION DROP CONSTRAINT CK_QUESTION_STATUS';
    END IF;
    EXECUTE IMMEDIATE q'[ALTER TABLE QUESTION ADD CONSTRAINT CK_QUESTION_STATUS CHECK (STATUS IN ('ACTIVE','ARCHIVED','DELETED'))]';

    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'APP_USER' AND CONSTRAINT_NAME = 'CK_APP_USER_STATUS';
    IF v_count > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_USER DROP CONSTRAINT CK_APP_USER_STATUS';
    END IF;
    EXECUTE IMMEDIATE q'[ALTER TABLE APP_USER ADD CONSTRAINT CK_APP_USER_STATUS CHECK (STATUS IN ('PENDING','ACTIVE','SUSPENDED','LOCKED','DISABLED','DELETED'))]';
END;
