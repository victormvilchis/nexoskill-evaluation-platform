DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'DELETED_AT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (DELETED_AT TIMESTAMP WITH TIME ZONE)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'DELETED_BY';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (DELETED_BY NUMBER)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'DELETE_REASON';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (DELETE_REASON VARCHAR2(500 CHAR))';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'APP_USER' AND COLUMN_NAME = 'DELETED_AT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_USER ADD (DELETED_AT TIMESTAMP WITH TIME ZONE)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'APP_USER' AND COLUMN_NAME = 'DELETED_BY';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_USER ADD (DELETED_BY NUMBER)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'APP_USER' AND COLUMN_NAME = 'DELETE_REASON';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE APP_USER ADD (DELETE_REASON VARCHAR2(500 CHAR))';
    END IF;
END;
