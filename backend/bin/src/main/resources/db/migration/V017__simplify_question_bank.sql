-- Simplified question bank migration.
-- This migration is intentionally idempotent because Oracle commits DDL and a
-- failed first execution may leave part of the structure already applied.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'STATEMENT_TEXT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (STATEMENT_TEXT CLOB)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'EXPLANATION_TEXT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (EXPLANATION_TEXT CLOB)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'CODE_LANGUAGE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (CODE_LANGUAGE VARCHAR2(40 CHAR))';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'CODE_CONTENT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (CODE_CONTENT CLOB)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'ACCEPTED_ANSWERS_JSON';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (ACCEPTED_ANSWERS_JSON CLOB)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'ANSWER_CASE_SENSITIVE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (ANSWER_CASE_SENSITIVE NUMBER(1) DEFAULT 0 NOT NULL)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'MANUAL_REVIEW';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (MANUAL_REVIEW NUMBER(1) DEFAULT 0 NOT NULL)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'NUMERIC_MIN';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (NUMERIC_MIN NUMBER)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'NUMERIC_MAX';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (NUMERIC_MAX NUMBER)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'NUMERIC_TOLERANCE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (NUMERIC_TOLERANCE NUMBER)';
    END IF;

    SELECT COUNT(*) INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'RESPONSE_MAX_LENGTH';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION ADD (RESPONSE_MAX_LENGTH NUMBER)';
    END IF;
END;
/

UPDATE QUESTION q
SET (STATEMENT_TEXT, EXPLANATION_TEXT) = (
    SELECT v.STATEMENT_TEXT, v.EXPLANATION_TEXT
    FROM QUESTION_VERSION v
    WHERE v.QUESTION_VERSION_ID = q.CURRENT_VERSION_ID
)
WHERE q.STATEMENT_TEXT IS NULL
  AND q.CURRENT_VERSION_ID IS NOT NULL;

