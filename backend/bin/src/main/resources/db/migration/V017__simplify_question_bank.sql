UPDATE QUESTION_OPTION qo
SET QUESTION_ID = (
    SELECT q.QUESTION_ID
    FROM QUESTION q
    WHERE q.CURRENT_VERSION_ID = qo.QUESTION_VERSION_ID
)
WHERE qo.QUESTION_ID IS NULL
  AND EXISTS (
      SELECT 1
      FROM QUESTION q
      WHERE q.CURRENT_VERSION_ID = qo.QUESTION_VERSION_ID
  );

DELETE FROM QUESTION_OPTION
WHERE QUESTION_ID IS NULL;

