DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES
    WHERE TABLE_NAME = 'QUESTION_CATEGORY_RELATION';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE QUESTION_CATEGORY_RELATION (
                QUESTION_ID NUMBER NOT NULL,
                CATEGORY_ID NUMBER NOT NULL,
                ASSIGNED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_QUESTION_CATEGORY_REL PRIMARY KEY (QUESTION_ID, CATEGORY_ID),
                CONSTRAINT FK_QCR_QUESTION FOREIGN KEY (QUESTION_ID) REFERENCES QUESTION (QUESTION_ID),
                CONSTRAINT FK_QCR_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES QUESTION_CATEGORY (CATEGORY_ID)
            )
        ]';
    END IF;
END;
/

MERGE INTO QUESTION_CATEGORY_RELATION target
USING (
    SELECT QUESTION_ID, CATEGORY_ID
    FROM QUESTION
    WHERE CATEGORY_ID IS NOT NULL
) source
ON (target.QUESTION_ID = source.QUESTION_ID AND target.CATEGORY_ID = source.CATEGORY_ID)
WHEN NOT MATCHED THEN
    INSERT (QUESTION_ID, CATEGORY_ID)
    VALUES (source.QUESTION_ID, source.CATEGORY_ID);

DECLARE
    v_nullable VARCHAR2(1);
BEGIN
    SELECT NULLABLE INTO v_nullable
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'QUESTION' AND COLUMN_NAME = 'CATEGORY_ID';
    IF v_nullable = 'N' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE QUESTION MODIFY (CATEGORY_ID NULL)';
    END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_QCR_CATEGORY ON QUESTION_CATEGORY_RELATION (CATEGORY_ID, QUESTION_ID)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE NOT IN (-955, -1408) THEN
            RAISE;
        END IF;
END;
