-- Administración integral de estudiantes y ciclos de certificación.
-- La migración conserva las columnas y tablas legadas; la nueva lectura/escritura se realiza
-- sobre fechas de calendario, cinco indicadores de aplicabilidad y ciclos normalizados.

DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('STUDENT', 'ACCESS_VALID_FROM', 'ACCESS_VALID_FROM DATE');
    add_column_if_missing('STUDENT', 'ACCESS_EXPIRES_ON', 'ACCESS_EXPIRES_ON DATE');
    add_column_if_missing('STUDENT', 'ADMISSION_DATE', 'ADMISSION_DATE DATE');
    add_column_if_missing('STUDENT', 'APPLIES_TECH_CERT', 'APPLIES_TECH_CERT NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('STUDENT', 'APPLIES_DEV_SECURITY', 'APPLIES_DEV_SECURITY NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('STUDENT', 'APPLIES_NORMATIVE_TESTING', 'APPLIES_NORMATIVE_TESTING NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('STUDENT', 'APPLIES_ONE', 'APPLIES_ONE NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('STUDENT', 'APPLIES_AGILE', 'APPLIES_AGILE NUMBER(1) DEFAULT 0 NOT NULL');

    add_column_if_missing('ORGANIZATION_CERTIFICATION_POLICY', 'RETRY_MONTHS', 'RETRY_MONTHS NUMBER');
    add_column_if_missing('ORGANIZATION_CERTIFICATION_POLICY', 'RETRY_DAYS', 'RETRY_DAYS NUMBER');
    add_column_if_missing('ORGANIZATION_CERTIFICATION_POLICY', 'VALIDITY_YEARS', 'VALIDITY_YEARS NUMBER');

    add_column_if_missing('STUDENT_CERTIFICATION_HISTORY', 'STUDENT_CERTIFICATION_CYCLE_ID', 'STUDENT_CERTIFICATION_CYCLE_ID NUMBER');
    add_column_if_missing('STUDENT_CERTIFICATION_HISTORY', 'STUDENT_CERTIFICATION_CYCLE_ATTEMPT_ID', 'STUDENT_CERTIFICATION_CYCLE_ATTEMPT_ID NUMBER');
END;
/

-- Backfill conservador de las tres fechas. Las columnas TSTZ legadas permanecen disponibles
-- para compatibilidad, pero el acceso operativo usa las nuevas columnas DATE.
UPDATE STUDENT
   SET ACCESS_VALID_FROM = NVL(ACCESS_VALID_FROM, TRUNC(CAST(VALID_FROM AS DATE))),
       ACCESS_EXPIRES_ON = NVL(ACCESS_EXPIRES_ON,
                               CASE WHEN EXPIRES_AT IS NULL THEN NULL ELSE TRUNC(CAST(EXPIRES_AT AS DATE)) END),
       ADMISSION_DATE = NVL(ADMISSION_DATE,
                            NVL(CERTIFICATION_ENROLLMENT_DATE,
                                (SELECT MAX(profile.ENROLLMENT_DATE)
                                   FROM STUDENT_CERTIFICATION_PROFILE profile
                                  WHERE profile.STUDENT_ID = STUDENT.STUDENT_ID)))
 WHERE ACCESS_VALID_FROM IS NULL
    OR (ACCESS_EXPIRES_ON IS NULL AND EXPIRES_AT IS NOT NULL)
    OR ADMISSION_DATE IS NULL;

-- Recupera los indicadores de aplicabilidad existentes sin crear ciclos incompletos.
UPDATE STUDENT s
   SET APPLIES_TECH_CERT = CASE WHEN EXISTS (
           SELECT 1 FROM STUDENT_CERTIFICATION_PROFILE p
           JOIN STUDENT_CERT_REQUIREMENT r
             ON r.STUDENT_CERTIFICATION_PROFILE_ID = p.STUDENT_CERTIFICATION_PROFILE_ID
          WHERE p.STUDENT_ID = s.STUDENT_ID
            AND r.CERTIFICATION_TYPE = 'TECHNOLOGICAL'
            AND r.APPLIES = 1) THEN 1 ELSE APPLIES_TECH_CERT END,
       APPLIES_DEV_SECURITY = CASE WHEN EXISTS (
           SELECT 1 FROM STUDENT_CERTIFICATION_PROFILE p
           JOIN STUDENT_CERT_REQUIREMENT r
             ON r.STUDENT_CERTIFICATION_PROFILE_ID = p.STUDENT_CERTIFICATION_PROFILE_ID
          WHERE p.STUDENT_ID = s.STUDENT_ID
            AND r.CERTIFICATION_TYPE = 'DEVELOPMENT_SECURITY'
            AND r.APPLIES = 1) THEN 1 ELSE APPLIES_DEV_SECURITY END,
       APPLIES_NORMATIVE_TESTING = CASE WHEN EXISTS (
           SELECT 1 FROM STUDENT_CERTIFICATION_PROFILE p
           JOIN STUDENT_CERT_REQUIREMENT r
             ON r.STUDENT_CERTIFICATION_PROFILE_ID = p.STUDENT_CERTIFICATION_PROFILE_ID
          WHERE p.STUDENT_ID = s.STUDENT_ID
            AND r.CERTIFICATION_TYPE = 'NORMATIVE_TESTING'
            AND r.APPLIES = 1) THEN 1 ELSE APPLIES_NORMATIVE_TESTING END,
       APPLIES_ONE = CASE WHEN EXISTS (
           SELECT 1 FROM STUDENT_CERTIFICATION_PROFILE p
           JOIN STUDENT_CERT_REQUIREMENT r
             ON r.STUDENT_CERTIFICATION_PROFILE_ID = p.STUDENT_CERTIFICATION_PROFILE_ID
          WHERE p.STUDENT_ID = s.STUDENT_ID
            AND r.CERTIFICATION_TYPE = 'ONE'
            AND r.APPLIES = 1) THEN 1 ELSE APPLIES_ONE END,
       APPLIES_AGILE = CASE WHEN EXISTS (
           SELECT 1 FROM STUDENT_CERTIFICATION_PROFILE p
           JOIN STUDENT_CERT_REQUIREMENT r
             ON r.STUDENT_CERTIFICATION_PROFILE_ID = p.STUDENT_CERTIFICATION_PROFILE_ID
          WHERE p.STUDENT_ID = s.STUDENT_ID
            AND r.CERTIFICATION_TYPE = 'AGILE'
            AND r.APPLIES = 1) THEN 1 ELSE APPLIES_AGILE END;

DECLARE
    PROCEDURE add_constraint_if_missing(p_table VARCHAR2, p_name VARCHAR2, p_sql VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_table)
           AND CONSTRAINT_NAME = UPPER(p_name);
        IF v_count = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
BEGIN
    add_constraint_if_missing('STUDENT', 'CK_STUDENT_ACCESS_DATES',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_ACCESS_DATES CHECK (ACCESS_VALID_FROM IS NOT NULL AND (ACCESS_EXPIRES_ON IS NULL OR ACCESS_EXPIRES_ON >= ACCESS_VALID_FROM))');
    add_constraint_if_missing('STUDENT', 'CK_STUDENT_CERT_FLAGS',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_CERT_FLAGS CHECK (APPLIES_TECH_CERT IN (0,1) AND APPLIES_DEV_SECURITY IN (0,1) AND APPLIES_NORMATIVE_TESTING IN (0,1) AND APPLIES_ONE IN (0,1) AND APPLIES_AGILE IN (0,1))');
    add_constraint_if_missing('STUDENT', 'CK_STUDENT_ADMISSION_REQUIRED',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_ADMISSION_REQUIRED CHECK ((APPLIES_TECH_CERT + APPLIES_DEV_SECURITY + APPLIES_NORMATIVE_TESTING + APPLIES_ONE + APPLIES_AGILE = 0) OR ADMISSION_DATE IS NOT NULL)');
    add_constraint_if_missing('ORGANIZATION_CERTIFICATION_POLICY', 'CK_ORG_CERT_POLICY_RETRY',
        'ALTER TABLE ORGANIZATION_CERTIFICATION_POLICY ADD CONSTRAINT CK_ORG_CERT_POLICY_RETRY CHECK ((RETRY_MONTHS IS NULL OR RETRY_MONTHS >= 0) AND (RETRY_DAYS IS NULL OR RETRY_DAYS >= 0) AND (VALIDITY_YEARS IS NULL OR VALIDITY_YEARS >= 1))');
END;
