-- Políticas predeterminadas confirmadas. ONE queda sin plazo, reintento ni vigencia.
MERGE INTO ORGANIZATION_CERTIFICATION_POLICY target
USING (
    SELECT o.ORGANIZATION_ID, rules.CERTIFICATION_TYPE,
           RAWTOHEX(SYS_GUID()) GUID_HEX,
           rules.DEADLINE_MONTHS, rules.DEADLINE_DAYS,
           rules.RETRY_MONTHS, rules.RETRY_DAYS, rules.VALIDITY_YEARS
      FROM ORGANIZATION o
      CROSS JOIN (
          SELECT 'TECHNOLOGICAL' CERTIFICATION_TYPE, 1 DEADLINE_MONTHS, 0 DEADLINE_DAYS, 0 RETRY_MONTHS, 15 RETRY_DAYS, 2 VALIDITY_YEARS FROM DUAL UNION ALL
          SELECT 'DEVELOPMENT_SECURITY', 3, 0, 1, 15, 2 FROM DUAL UNION ALL
          SELECT 'NORMATIVE_TESTING', 2, 0, 1, 0, 2 FROM DUAL UNION ALL
          SELECT 'ONE', NULL, NULL, NULL, NULL, NULL FROM DUAL UNION ALL
          SELECT 'AGILE', 3, 0, 1, 15, NULL FROM DUAL
      ) rules
     WHERE o.ORGANIZATION_TYPE = 'CUSTOMER'
) source
ON (target.ORGANIZATION_ID = source.ORGANIZATION_ID AND target.CERTIFICATION_TYPE = source.CERTIFICATION_TYPE)
WHEN MATCHED THEN UPDATE SET
    target.DEADLINE_MONTHS = source.DEADLINE_MONTHS,
    target.DEADLINE_DAYS = source.DEADLINE_DAYS,
    target.RETRY_MONTHS = source.RETRY_MONTHS,
    target.RETRY_DAYS = source.RETRY_DAYS,
    target.VALIDITY_YEARS = source.VALIDITY_YEARS,
    target.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    PUBLIC_ID, ORGANIZATION_ID, CERTIFICATION_TYPE, APPLIES_BY_DEFAULT,
    DEADLINE_MONTHS, DEADLINE_DAYS, RETRY_MONTHS, RETRY_DAYS, VALIDITY_YEARS,
    STATUS, CREATED_AT, UPDATED_AT, VERSION_NO
) VALUES (
    LOWER(SUBSTR(source.GUID_HEX, 1, 8) || '-' ||
          SUBSTR(source.GUID_HEX, 9, 4) || '-' ||
          SUBSTR(source.GUID_HEX, 13, 4) || '-' ||
          SUBSTR(source.GUID_HEX, 17, 4) || '-' ||
          SUBSTR(source.GUID_HEX, 21, 12)),
    source.ORGANIZATION_ID, source.CERTIFICATION_TYPE, 0,
    source.DEADLINE_MONTHS, source.DEADLINE_DAYS,
    source.RETRY_MONTHS, source.RETRY_DAYS, source.VALIDITY_YEARS,
    'ACTIVE', SYSTIMESTAMP, SYSTIMESTAMP, 0
);

-- La matriz operativa de estudiantes y certificaciones se homologa para los tres roles.
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
  FROM APP_ROLE r
 CROSS JOIN APP_PERMISSION p
 WHERE r.ROLE_CODE IN ('ADMINISTRATOR','MANAGER','SUPERVISOR')
   AND p.PERMISSION_CODE IN (
       'STUDENT_VIEW','STUDENT_CREATE','STUDENT_UPDATE','STUDENT_STATUS_CHANGE',
       'STUDENT_PASSWORD_RESET','STUDENT_SESSION_MANAGE','STUDENT_DELETE',
       'STUDENT_CERTIFICATION_MANAGE','STUDENT_CERTIFICATION_CATALOG_VIEW'
   )
   AND NOT EXISTS (
       SELECT 1 FROM APP_ROLE_PERMISSION rp
        WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID
   );

