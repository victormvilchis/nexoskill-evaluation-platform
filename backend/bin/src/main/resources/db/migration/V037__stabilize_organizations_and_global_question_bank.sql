        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = UPPER(p_name);
        IF v_count = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
BEGIN
    add_constraint_if_missing('FK_ORG_STATUS_CHANGED_BY',
