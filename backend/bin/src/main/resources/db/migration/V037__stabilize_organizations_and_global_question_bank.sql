UPDATE ORGANIZATION
   SET STATUS_CHANGED_AT = NVL(STATUS_CHANGED_AT, UPDATED_AT),
       STATUS_CHANGED_BY = NVL(STATUS_CHANGED_BY, UPDATED_BY)
 WHERE STATUS_CHANGED_AT IS NULL OR STATUS_CHANGED_BY IS NULL;

