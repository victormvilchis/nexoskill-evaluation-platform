DECLARE
    PROCEDURE create_index_if_missing(p_name VARCHAR2, p_sql VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_INDEXES
         WHERE INDEX_NAME = UPPER(p_name);

        IF v_count = 0 THEN
            BEGIN
                EXECUTE IMMEDIATE p_sql;
            EXCEPTION
                WHEN OTHERS THEN
                    -- ORA-01408: la misma lista de columnas ya esta indexada
                    -- ORA-00955: el nombre del objeto ya existe
                    IF SQLCODE NOT IN (-1408, -955) THEN
                        RAISE;
                    END IF;
            END;
        END IF;
    END;
BEGIN
    create_index_if_missing('IX_ORG_STATUS_HISTORY_ORG',
        'CREATE INDEX IX_ORG_STATUS_HISTORY_ORG ON ORGANIZATION_STATUS_HISTORY (ORGANIZATION_ID, CHANGED_AT DESC)');
    create_index_if_missing('IX_STUDENT_ORG_STATUS_COUNT',
        'CREATE INDEX IX_STUDENT_ORG_STATUS_COUNT ON STUDENT (ORGANIZATION_ID, STATUS)');
    create_index_if_missing('IX_QUESTION_TECH_STATUS',
        'CREATE INDEX IX_QUESTION_TECH_STATUS ON QUESTION_TECHNOLOGY (STATUS, DISPLAY_ORDER, TECHNOLOGY_NAME)');
    create_index_if_missing('IX_QUESTION_GOVERNANCE_FILTERS',
        'CREATE INDEX IX_QUESTION_GOVERNANCE_FILTERS ON QUESTION (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, STATUS, TECHNOLOGY_ID, DIFFICULTY_CODE, UPDATED_AT)');
    create_index_if_missing('IX_QUESTION_SOURCE_ORG',
        'CREATE INDEX IX_QUESTION_SOURCE_ORG ON QUESTION (SOURCE_ORGANIZATION_ID, SOURCE_ORGANIZATION_QUESTION_ID, SOURCE_ORGANIZATION_VERSION)');
END;
