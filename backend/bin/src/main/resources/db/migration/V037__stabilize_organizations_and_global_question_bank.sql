DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_column || ' ' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('ORGANIZATION', 'STATUS_CHANGED_AT', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('ORGANIZATION', 'STATUS_CHANGED_BY', 'NUMBER');
    add_column_if_missing('ORGANIZATION', 'STATUS_REASON', 'VARCHAR2(500 CHAR)');
    add_column_if_missing('ORGANIZATION', 'DELETED_AT', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('ORGANIZATION', 'DELETED_BY', 'NUMBER');

    add_column_if_missing('QUESTION', 'TECHNOLOGY_ID', 'NUMBER');
    add_column_if_missing('QUESTION', 'LEVEL_CODE', 'VARCHAR2(30 CHAR)');
    add_column_if_missing('QUESTION', 'SOURCE_ORGANIZATION_ID', 'NUMBER');
    add_column_if_missing('QUESTION', 'SOURCE_ORGANIZATION_QUESTION_ID', 'NUMBER');
    add_column_if_missing('QUESTION', 'SOURCE_ORGANIZATION_VERSION', 'NUMBER');
    add_column_if_missing('QUESTION', 'CLONED_TO_GLOBAL_AT', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('QUESTION', 'CLONED_TO_GLOBAL_BY', 'NUMBER');
END;
