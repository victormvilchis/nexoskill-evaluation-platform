-- Ciclo de vida de certificaciones importadas, trazabilidad e incorporación de Jira.
-- Separa resultados administrativos del Excel de los intentos manuales explícitos.

DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('STUDENT', 'APPLIES_JIRA',
        'APPLIES_JIRA NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'LATEST_EXAM_STATUS',
        'LATEST_EXAM_STATUS VARCHAR2(30 CHAR) DEFAULT ''NOT_SCHEDULED'' NOT NULL');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'LATEST_SCORE',
        'LATEST_SCORE NUMBER(5,2)');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'LAST_APPROVED_APPLICATION_DATE',
        'LAST_APPROVED_APPLICATION_DATE DATE');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'IMPORTED_FAILURE_COUNT',
        'IMPORTED_FAILURE_COUNT NUMBER');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'RESULT_SOURCE',
        'RESULT_SOURCE VARCHAR2(20 CHAR)');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'LAST_IMPORT_FINGERPRINT',
        'LAST_IMPORT_FINGERPRINT VARCHAR2(64 CHAR)');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'LAST_IMPORTED_AT',
        'LAST_IMPORTED_AT TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('STUDENT_CERTIFICATION_CYCLE', 'LAST_IMPORTED_BY',
        'LAST_IMPORTED_BY NUMBER');
END;
/

-- Conserva el último resultado manual existente como resumen inicial, sin crear intentos nuevos.
MERGE INTO STUDENT_CERTIFICATION_CYCLE cycle
USING (
    SELECT STUDENT_CERTIFICATION_CYCLE_ID, EXAM_STATUS, SCORE
      FROM (
          SELECT a.STUDENT_CERTIFICATION_CYCLE_ID, a.EXAM_STATUS, a.SCORE,
                 ROW_NUMBER() OVER (
                     PARTITION BY a.STUDENT_CERTIFICATION_CYCLE_ID
                     ORDER BY a.ATTEMPT_NUMBER DESC,
                              a.STUDENT_CERTIFICATION_CYCLE_ATTEMPT_ID DESC) RN
            FROM STUDENT_CERTIFICATION_CYCLE_ATTEMPT a
      )
     WHERE RN = 1
) latest
ON (cycle.STUDENT_CERTIFICATION_CYCLE_ID = latest.STUDENT_CERTIFICATION_CYCLE_ID)
WHEN MATCHED THEN UPDATE SET
    cycle.LATEST_EXAM_STATUS = latest.EXAM_STATUS,
    cycle.LATEST_SCORE = latest.SCORE,
    cycle.RESULT_SOURCE = NVL(cycle.RESULT_SOURCE, 'MANUAL')
WHERE cycle.RESULT_SOURCE IS NULL;

UPDATE STUDENT_CERTIFICATION_CYCLE
   SET LATEST_EXAM_STATUS = CASE
           WHEN APPROVED = 1 THEN 'PASSED'
           WHEN APPROVED = 0 AND APPLICATION_DATE IS NOT NULL THEN 'FAILED'
           WHEN APPLICATION_DATE IS NOT NULL THEN 'COMPLETED'
           ELSE LATEST_EXAM_STATUS
       END,
       RESULT_SOURCE = CASE
           WHEN APPROVED IS NOT NULL OR APPLICATION_DATE IS NOT NULL THEN 'MANUAL'
           ELSE RESULT_SOURCE
       END
 WHERE RESULT_SOURCE IS NULL;

-- Conserva la fecha de la última aprobación real, separada de la última presentación.
MERGE INTO STUDENT_CERTIFICATION_CYCLE cycle
USING (
    SELECT STUDENT_CERTIFICATION_CYCLE_ID, MAX(APPLICATION_DATE) LAST_APPROVED_DATE
      FROM STUDENT_CERTIFICATION_CYCLE_ATTEMPT
     WHERE APPROVED = 1
       AND APPLICATION_DATE IS NOT NULL
     GROUP BY STUDENT_CERTIFICATION_CYCLE_ID
) approved_attempt
ON (cycle.STUDENT_CERTIFICATION_CYCLE_ID = approved_attempt.STUDENT_CERTIFICATION_CYCLE_ID)
WHEN MATCHED THEN UPDATE SET
    cycle.LAST_APPROVED_APPLICATION_DATE = NVL(
        cycle.LAST_APPROVED_APPLICATION_DATE,
        approved_attempt.LAST_APPROVED_DATE
    );

UPDATE STUDENT_CERTIFICATION_CYCLE
   SET LAST_APPROVED_APPLICATION_DATE = NVL(LAST_APPROVED_APPLICATION_DATE, APPLICATION_DATE)
 WHERE APPROVED = 1
   AND APPLICATION_DATE IS NOT NULL;

-- ONE, Agile y Jira conservan su historial, pero el ciclo operativo no administra fechas,
-- examen, intentos ni vigencia. Esto también normaliza posibles datos legados de Agile/ONE.
UPDATE STUDENT_CERTIFICATION_CYCLE
   SET DEADLINE_DATE = NULL,
       SCHEDULED_DATE = NULL,
       APPLICATION_DATE = NULL,
       LAST_APPROVED_APPLICATION_DATE = NULL,
       EXPIRATION_DATE = NULL,
       VALIDITY_STATUS = 'NOT_OBTAINED',
       PROCESS_TYPE = 'CERTIFICATION',
       LATEST_EXAM_STATUS = 'NOT_SCHEDULED',
       LATEST_SCORE = NULL,
       IMPORTED_FAILURE_COUNT = NULL
 WHERE CERTIFICATION_TYPE IN ('ONE','AGILE','JIRA');

DECLARE
    PROCEDURE drop_constraint_if_exists(p_table VARCHAR2, p_name VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_table)
           AND CONSTRAINT_NAME = UPPER(p_name);
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' DROP CONSTRAINT ' || p_name;
        END IF;
    END;
    PROCEDURE add_constraint_if_missing(p_table VARCHAR2, p_name VARCHAR2, p_sql VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_table)
           AND CONSTRAINT_NAME = UPPER(p_name);
        IF v_count = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
BEGIN
    drop_constraint_if_exists('STUDENT', 'CK_STUDENT_CERT_FLAGS');
    drop_constraint_if_exists('STUDENT', 'CK_STUDENT_ADMISSION_REQUIRED');
    drop_constraint_if_exists('ORGANIZATION_CERTIFICATION_POLICY', 'CK_ORG_CERT_POLICY_TYPE');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_TYPE');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_NO_EXPIRY');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_EXPIRY');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_LATEST_EXAM');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_LATEST_SCORE');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_FAILURES');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_SOURCE');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_CYCLE', 'FK_STUDENT_CERT_CYCLE_IMPORT_BY');

    add_constraint_if_missing('STUDENT', 'CK_STUDENT_CERT_FLAGS',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_CERT_FLAGS CHECK (' ||
        'APPLIES_TECH_CERT IN (0,1) AND APPLIES_DEV_SECURITY IN (0,1) AND ' ||
        'APPLIES_NORMATIVE_TESTING IN (0,1) AND APPLIES_ONE IN (0,1) AND ' ||
        'APPLIES_AGILE IN (0,1) AND APPLIES_JIRA IN (0,1))');
    add_constraint_if_missing('STUDENT', 'CK_STUDENT_ADMISSION_REQUIRED',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_ADMISSION_REQUIRED CHECK (' ||
        '(APPLIES_TECH_CERT + APPLIES_DEV_SECURITY + APPLIES_NORMATIVE_TESTING + ' ||
        'APPLIES_ONE + APPLIES_AGILE + APPLIES_JIRA = 0) OR ADMISSION_DATE IS NOT NULL)');
    add_constraint_if_missing('ORGANIZATION_CERTIFICATION_POLICY', 'CK_ORG_CERT_POLICY_TYPE',
        'ALTER TABLE ORGANIZATION_CERTIFICATION_POLICY ADD CONSTRAINT CK_ORG_CERT_POLICY_TYPE CHECK (' ||
        'CERTIFICATION_TYPE IN (''DEVELOPMENT_SECURITY'',''TECHNOLOGICAL'',''ONE'',' ||
        '''NORMATIVE_TESTING'',''AGILE'',''JIRA''))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_TYPE',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_TYPE CHECK (' ||
        'CERTIFICATION_TYPE IN (''DEVELOPMENT_SECURITY'',''TECHNOLOGICAL'',''ONE'',' ||
        '''NORMATIVE_TESTING'',''AGILE'',''JIRA''))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_NO_EXPIRY',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_NO_EXPIRY CHECK (' ||
        '(CERTIFICATION_TYPE IN (''ONE'',''AGILE'',''JIRA'') AND DEADLINE_DATE IS NULL ' ||
        'AND SCHEDULED_DATE IS NULL AND APPLICATION_DATE IS NULL ' ||
        'AND LAST_APPROVED_APPLICATION_DATE IS NULL AND EXPIRATION_DATE IS NULL ' ||
        'AND VALIDITY_STATUS = ''NOT_OBTAINED'' AND PROCESS_TYPE = ''CERTIFICATION'') OR ' ||
        'CERTIFICATION_TYPE NOT IN (''ONE'',''AGILE'',''JIRA''))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_LATEST_EXAM',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_LATEST_EXAM CHECK (' ||
        'LATEST_EXAM_STATUS IN (''NOT_SCHEDULED'',''SCHEDULED'',''RESCHEDULED'',''COMPLETED'',' ||
        '''PASSED'',''FAILED'',''ABSENT'',''CANCELLED''))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_LATEST_SCORE',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_LATEST_SCORE CHECK (' ||
        'LATEST_SCORE IS NULL OR (LATEST_SCORE >= 0 AND LATEST_SCORE <= 100))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_FAILURES',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_FAILURES CHECK (' ||
        'IMPORTED_FAILURE_COUNT IS NULL OR (IMPORTED_FAILURE_COUNT >= 0 AND ' ||
        'IMPORTED_FAILURE_COUNT = TRUNC(IMPORTED_FAILURE_COUNT)))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_SOURCE',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_SOURCE CHECK (' ||
        'RESULT_SOURCE IS NULL OR RESULT_SOURCE IN (''IMPORT'',''MANUAL''))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'CK_STUDENT_CERT_CYCLE_EXPIRY',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT CK_STUDENT_CERT_CYCLE_EXPIRY CHECK (' ||
        'EXPIRATION_DATE IS NULL OR (APPROVED = 1 AND LAST_APPROVED_APPLICATION_DATE IS NOT NULL ' ||
        'AND EXPIRATION_DATE >= LAST_APPROVED_APPLICATION_DATE))');
    add_constraint_if_missing('STUDENT_CERTIFICATION_CYCLE', 'FK_STUDENT_CERT_CYCLE_IMPORT_BY',
        'ALTER TABLE STUDENT_CERTIFICATION_CYCLE ADD CONSTRAINT FK_STUDENT_CERT_CYCLE_IMPORT_BY ' ||
        'FOREIGN KEY (LAST_IMPORTED_BY) REFERENCES APP_USER (USER_ID)');
END;
/

-- Corrige las reglas funcionales vigentes y agrega Jira sin fechas ni intentos.
UPDATE ORGANIZATION_CERTIFICATION_POLICY
   SET DEADLINE_MONTHS = CASE CERTIFICATION_TYPE
           WHEN 'TECHNOLOGICAL' THEN 1
           WHEN 'DEVELOPMENT_SECURITY' THEN 3
           WHEN 'NORMATIVE_TESTING' THEN 2
           ELSE NULL END,
       DEADLINE_DAYS = CASE WHEN CERTIFICATION_TYPE IN ('TECHNOLOGICAL','DEVELOPMENT_SECURITY','NORMATIVE_TESTING') THEN 0 ELSE NULL END,
       VALIDITY_YEARS = CASE CERTIFICATION_TYPE
           WHEN 'TECHNOLOGICAL' THEN 2
           WHEN 'DEVELOPMENT_SECURITY' THEN 1
           WHEN 'NORMATIVE_TESTING' THEN 1
           ELSE NULL END,
       RETRY_MONTHS = CASE WHEN CERTIFICATION_TYPE IN ('ONE','AGILE','JIRA') THEN NULL ELSE RETRY_MONTHS END,
       RETRY_DAYS = CASE WHEN CERTIFICATION_TYPE IN ('ONE','AGILE','JIRA') THEN NULL ELSE RETRY_DAYS END,
       UPDATED_AT = SYSTIMESTAMP
 WHERE CERTIFICATION_TYPE IN ('TECHNOLOGICAL','DEVELOPMENT_SECURITY','NORMATIVE_TESTING','ONE','AGILE','JIRA');

MERGE INTO ORGANIZATION_CERTIFICATION_POLICY target
USING (
    SELECT base.ORGANIZATION_ID,
           LOWER(SUBSTR(base.GUID_HEX,1,8) || '-' ||
                 SUBSTR(base.GUID_HEX,9,4) || '-' ||
                 SUBSTR(base.GUID_HEX,13,4) || '-' ||
                 SUBSTR(base.GUID_HEX,17,4) || '-' ||
                 SUBSTR(base.GUID_HEX,21,12)) PUBLIC_ID
      FROM (
          SELECT o.ORGANIZATION_ID, RAWTOHEX(SYS_GUID()) GUID_HEX
            FROM ORGANIZATION o
           WHERE o.ORGANIZATION_TYPE = 'CUSTOMER'
      ) base
) source
ON (target.ORGANIZATION_ID = source.ORGANIZATION_ID AND target.CERTIFICATION_TYPE = 'JIRA')
WHEN NOT MATCHED THEN INSERT (
    PUBLIC_ID, ORGANIZATION_ID, CERTIFICATION_TYPE, APPLIES_BY_DEFAULT,
    DEADLINE_MONTHS, DEADLINE_DAYS, MAX_ATTEMPTS, STATUS,
    CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT, VERSION_NO,
    RETRY_MONTHS, RETRY_DAYS, VALIDITY_YEARS
) VALUES (
    source.PUBLIC_ID, source.ORGANIZATION_ID, 'JIRA', 0,
    NULL, NULL, NULL, 'ACTIVE', NULL, NULL, SYSTIMESTAMP, SYSTIMESTAMP, 0,
    NULL, NULL, NULL
);
