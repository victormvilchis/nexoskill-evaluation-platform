MERGE INTO APP_PERMISSION target
USING (
    SELECT 'GLOBAL_CONTENT_REVIEW' code, 'Revisar contenido de todas las organizaciones' name FROM DUAL UNION ALL
    SELECT 'GLOBAL_CONTENT_PROMOTE', 'Promover contenido organizacional a global' FROM DUAL UNION ALL
    SELECT 'GLOBAL_CONTENT_PUBLISH', 'Publicar contenido global' FROM DUAL UNION ALL
    SELECT 'GLOBAL_CONTENT_DISTRIBUTE', 'Distribuir contenido global' FROM DUAL UNION ALL
    SELECT 'GLOBAL_CONTENT_VERSION_MANAGE', 'Administrar versiones globales' FROM DUAL UNION ALL
    SELECT 'GLOBAL_CONTENT_USE', 'Utilizar contenido global habilitado' FROM DUAL UNION ALL
    SELECT 'GLOBAL_CONTENT_CLONE', 'Clonar contenido global habilitado' FROM DUAL
) source
ON (target.PERMISSION_CODE = source.code)
WHEN NOT MATCHED THEN INSERT (PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION)
VALUES (source.code, source.name, 'GLOBAL_CONTENT', source.name);

