-- Todo contenido GLOBAL pertenece a la organización técnica GLOBAL. Se reemplazan
-- las restricciones de V029 antes de migrar los registros existentes.
DECLARE
    v_global_id NUMBER;

    PROCEDURE drop_constraint_if_exists(p_table VARCHAR2, p_constraint VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_table)
           AND CONSTRAINT_NAME = UPPER(p_constraint);
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' DROP CONSTRAINT ' || p_constraint;
        END IF;
    END;
BEGIN
    drop_constraint_if_exists('QUESTION', 'CK_QUESTION_SCOPE');
    drop_constraint_if_exists('QUESTION_CATEGORY', 'CK_QUESTION_CATEGORY_SCOPE');
    drop_constraint_if_exists('EVALUATION_FORM', 'CK_FORM_SCOPE');
    drop_constraint_if_exists('LEARNING_COLLECTION', 'CK_COLLECTION_SCOPE');

    SELECT ORGANIZATION_ID INTO v_global_id
      FROM ORGANIZATION
     WHERE ORGANIZATION_TYPE = 'GLOBAL';

    UPDATE QUESTION
       SET OWNER_ORGANIZATION_ID = v_global_id
     WHERE CONTENT_SCOPE = 'GLOBAL';
    UPDATE QUESTION_CATEGORY
       SET OWNER_ORGANIZATION_ID = v_global_id
     WHERE CONTENT_SCOPE = 'GLOBAL';
    UPDATE EVALUATION_FORM
       SET OWNER_ORGANIZATION_ID = v_global_id
     WHERE CONTENT_SCOPE = 'GLOBAL';
    UPDATE LEARNING_COLLECTION
       SET OWNER_ORGANIZATION_ID = v_global_id
     WHERE CONTENT_SCOPE = 'GLOBAL';
END;
/

