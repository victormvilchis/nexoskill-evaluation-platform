DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'STUDENT'
       AND CONSTRAINT_NAME = 'CK_STUDENT_ADMISSION_REQUIRED';

    IF v_count > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE STUDENT DROP CONSTRAINT CK_STUDENT_ADMISSION_REQUIRED';
    END IF;
END;
/
