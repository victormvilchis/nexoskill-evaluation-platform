UPDATE QUESTION_VERSION qv
SET VERSION_STATUS = (
    SELECT q.STATUS
    FROM QUESTION q
    WHERE q.QUESTION_ID = qv.QUESTION_ID
      AND q.CURRENT_VERSION_ID = qv.QUESTION_VERSION_ID
)
WHERE EXISTS (
    SELECT 1
    FROM QUESTION q
    WHERE q.QUESTION_ID = qv.QUESTION_ID
      AND q.CURRENT_VERSION_ID = qv.QUESTION_VERSION_ID
);

UPDATE QUESTION_VERSION qv
SET VERSION_STATUS = 'ARCHIVED'
WHERE NOT EXISTS (
    SELECT 1
    FROM QUESTION q
    WHERE q.CURRENT_VERSION_ID = qv.QUESTION_VERSION_ID
)
AND EXISTS (
    SELECT 1
    FROM QUESTION q
    WHERE q.QUESTION_ID = qv.QUESTION_ID
);

UPDATE QUESTION
SET PUBLISHED_VERSION_ID = CURRENT_VERSION_ID
WHERE STATUS = 'PUBLISHED';
