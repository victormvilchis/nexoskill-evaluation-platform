MERGE INTO APP_PERMISSION p
USING (
  SELECT 'FORM_VIEW' CODE, 'Consultar formularios' NAME, 'FORMS' MODULE, 'Permite consultar formularios.' DESCRIPTION FROM DUAL UNION ALL
  SELECT 'FORM_CREATE', 'Crear formularios', 'FORMS', 'Permite crear formularios.' FROM DUAL UNION ALL
  SELECT 'FORM_UPDATE', 'Editar formularios', 'FORMS', 'Permite editar formularios.' FROM DUAL UNION ALL
  SELECT 'FORM_STATUS_CHANGE', 'Cambiar estado de formularios', 'FORMS', 'Permite activar, deshabilitar, cerrar o archivar formularios.' FROM DUAL UNION ALL
  SELECT 'FORM_PREVIEW', 'Previsualizar formularios', 'FORMS', 'Permite consultar la vista previa administrativa.' FROM DUAL
) src
ON (p.PERMISSION_CODE = src.CODE)
WHEN NOT MATCHED THEN
  INSERT (PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION)
  VALUES (src.CODE, src.NAME, src.MODULE, src.DESCRIPTION);

MERGE INTO APP_ROLE_PERMISSION rp
USING (
  SELECT r.ROLE_ID, p.PERMISSION_ID
  FROM APP_ROLE r CROSS JOIN APP_PERMISSION p
  WHERE r.ROLE_CODE='ADMINISTRATOR'
    AND p.PERMISSION_CODE IN ('FORM_VIEW','FORM_CREATE','FORM_UPDATE','FORM_STATUS_CHANGE','FORM_PREVIEW')
) src
ON (rp.ROLE_ID=src.ROLE_ID AND rp.PERMISSION_ID=src.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID) VALUES (src.ROLE_ID, src.PERMISSION_ID);
