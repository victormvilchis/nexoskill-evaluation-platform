CREATE TABLE CERTIFICATION_PROFILE_CATALOG (
    CERTIFICATION_PROFILE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    PROFILE_CODE VARCHAR2(120 CHAR) NOT NULL,
    PROFILE_NAME VARCHAR2(200 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    SUGGESTED_TECH_PROFILE VARCHAR2(40 CHAR),
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CERT_PROFILE_CATALOG PRIMARY KEY (CERTIFICATION_PROFILE_ID),
    CONSTRAINT UK_CERT_PROFILE_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_CERT_PROFILE_CODE UNIQUE (PROFILE_CODE),
    CONSTRAINT CK_CERT_PROFILE_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE')),
    CONSTRAINT CK_CERT_PROFILE_TECH CHECK (
        SUGGESTED_TECH_PROFILE IS NULL OR
        SUGGESTED_TECH_PROFILE IN ('DEVELOPER','FUNCTIONAL','SPECIALIZED_PLATFORM')
    )
);

