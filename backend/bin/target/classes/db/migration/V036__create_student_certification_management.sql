        (DEADLINE_MONTHS IS NULL OR DEADLINE_MONTHS >= 0) AND
        (DEADLINE_DAYS IS NULL OR DEADLINE_DAYS >= 0)
    ),
    CONSTRAINT CK_ORG_CERT_POLICY_ATTEMPTS CHECK (MAX_ATTEMPTS IS NULL OR MAX_ATTEMPTS >= 1)
