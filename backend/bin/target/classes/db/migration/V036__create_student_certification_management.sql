INSERT INTO ORGANIZATION_CERTIFICATION_POLICY
    (PUBLIC_ID, ORGANIZATION_ID, CERTIFICATION_TYPE, APPLIES_BY_DEFAULT,
     DEADLINE_MONTHS, DEADLINE_DAYS, STATUS, CREATED_AT, UPDATED_AT, VERSION_NO)
SELECT LOWER(
           SUBSTR(RAWTOHEX(SYS_GUID()), 1, 8) || '-' ||
           SUBSTR(RAWTOHEX(SYS_GUID()), 9, 4) || '-' ||
           SUBSTR(RAWTOHEX(SYS_GUID()), 13, 4) || '-' ||
           SUBSTR(RAWTOHEX(SYS_GUID()), 17, 4) || '-' ||
           SUBSTR(RAWTOHEX(SYS_GUID()), 21, 12)
       ),
       o.ORGANIZATION_ID,
       t.CERTIFICATION_TYPE,
       0,
       t.DEADLINE_MONTHS,
       t.DEADLINE_DAYS,
       'ACTIVE',
       SYSTIMESTAMP,
       SYSTIMESTAMP,
       0
  FROM ORGANIZATION o
 CROSS JOIN (
     SELECT 'DEVELOPMENT_SECURITY' CERTIFICATION_TYPE, 2 DEADLINE_MONTHS, 15 DEADLINE_DAYS FROM DUAL UNION ALL
     SELECT 'TECHNOLOGICAL', NULL, NULL FROM DUAL UNION ALL
     SELECT 'ONE', NULL, NULL FROM DUAL UNION ALL
     SELECT 'NORMATIVE_TESTING', 2, 0 FROM DUAL UNION ALL
     SELECT 'AGILE', NULL, NULL FROM DUAL
 ) t
 WHERE o.ORGANIZATION_TYPE = 'CUSTOMER'
   AND NOT EXISTS (
       SELECT 1 FROM ORGANIZATION_CERTIFICATION_POLICY p
        WHERE p.ORGANIZATION_ID = o.ORGANIZATION_ID
          AND p.CERTIFICATION_TYPE = t.CERTIFICATION_TYPE
   );

