CREATE TABLE ORGANIZATION_CERTIFICATION_POLICY (
    ORGANIZATION_CERT_POLICY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    ORGANIZATION_ID NUMBER NOT NULL,
    CERTIFICATION_TYPE VARCHAR2(40 CHAR) NOT NULL,
    APPLIES_BY_DEFAULT NUMBER(1) DEFAULT 0 NOT NULL,
    DEADLINE_MONTHS NUMBER,
    DEADLINE_DAYS NUMBER,
    MAX_ATTEMPTS NUMBER,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY NUMBER,
    UPDATED_BY NUMBER,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORG_CERT_POLICY PRIMARY KEY (ORGANIZATION_CERT_POLICY_ID),
