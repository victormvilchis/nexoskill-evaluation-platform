ALTER TABLE APP_USER ADD (
    PASSWORD_CHANGE_REQUIRED NUMBER(1) DEFAULT 0 NOT NULL,
    PASSWORD_CHANGED_AT TIMESTAMP WITH TIME ZONE,
    TEMP_PASSWORD_EXPIRES_AT TIMESTAMP WITH TIME ZONE
);

ALTER TABLE APP_USER ADD CONSTRAINT CK_APP_USER_PASSWORD_CHANGE
    CHECK (PASSWORD_CHANGE_REQUIRED IN (0, 1));

UPDATE APP_USER
SET PASSWORD_CHANGED_AT = COALESCE(LAST_LOGIN_AT, CREATED_AT)
WHERE PASSWORD_CHANGED_AT IS NULL;

CREATE TABLE PASSWORD_HISTORY (
    PASSWORD_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_PASSWORD_HISTORY PRIMARY KEY (PASSWORD_HISTORY_ID),
    CONSTRAINT FK_PASSWORD_HISTORY_USER
        FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID)
);

CREATE INDEX IX_PASSWORD_HISTORY_USER_DATE
    ON PASSWORD_HISTORY (USER_ID, CREATED_AT DESC);

