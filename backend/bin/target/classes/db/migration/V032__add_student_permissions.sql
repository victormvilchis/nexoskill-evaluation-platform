MERGE INTO APP_PERMISSION target
USING (
    SELECT 'STUDENT_VIEW' code, 'Consultar estudiantes' name FROM DUAL UNION ALL
    SELECT 'STUDENT_CREATE', 'Crear estudiantes' FROM DUAL UNION ALL
    SELECT 'STUDENT_UPDATE', 'Modificar estudiantes' FROM DUAL UNION ALL
    SELECT 'STUDENT_STATUS_CHANGE', 'Administrar estado de estudiantes' FROM DUAL UNION ALL
    SELECT 'STUDENT_PASSWORD_RESET', 'Restablecer contraseña de estudiantes' FROM DUAL UNION ALL
    SELECT 'STUDENT_SESSION_MANAGE', 'Administrar sesiones de estudiantes' FROM DUAL
) source
ON (target.PERMISSION_CODE = source.code)
WHEN NOT MATCHED THEN INSERT (PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION)
VALUES (source.code, source.name, 'STUDENTS', source.name);

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM APP_ROLE r CROSS JOIN APP_PERMISSION p
WHERE r.ROLE_CODE = 'ADMINISTRATOR'
  AND p.MODULE_CODE = 'STUDENTS'
  AND NOT EXISTS (
      SELECT 1 FROM APP_ROLE_PERMISSION rp
      WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID
  );

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM APP_ROLE r CROSS JOIN APP_PERMISSION p
WHERE r.ROLE_CODE = 'MANAGER'
  AND p.PERMISSION_CODE IN (
      'STUDENT_VIEW','STUDENT_CREATE','STUDENT_UPDATE','STUDENT_STATUS_CHANGE',
      'STUDENT_PASSWORD_RESET','STUDENT_SESSION_MANAGE'
  )
  AND NOT EXISTS (
      SELECT 1 FROM APP_ROLE_PERMISSION rp
      WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID
  );

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM APP_ROLE r CROSS JOIN APP_PERMISSION p
WHERE r.ROLE_CODE = 'SUPERVISOR'
  AND p.PERMISSION_CODE IN ('STUDENT_VIEW','STUDENT_SESSION_MANAGE')
  AND NOT EXISTS (
      SELECT 1 FROM APP_ROLE_PERMISSION rp
      WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID
  );
