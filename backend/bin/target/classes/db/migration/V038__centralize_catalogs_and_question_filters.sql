        'ALTER TABLE QUESTION_DIFFICULTY_CATALOG ADD CONSTRAINT FK_QUESTION_DIFF_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID)');
