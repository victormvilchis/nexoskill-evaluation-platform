DECLARE
    PROCEDURE create_index_if_missing(p_name VARCHAR2, p_sql VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = UPPER(p_name);
        IF v_count = 0 THEN
            BEGIN
                EXECUTE IMMEDIATE p_sql;
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE NOT IN (-1408, -955) THEN RAISE; END IF;
            END;
        END IF;
    END;
BEGIN
    create_index_if_missing('IX_CERT_TECH_MASTER',
        'CREATE INDEX IX_CERT_TECH_MASTER ON CERTIFICATION_TECHNOLOGY_CATALOG (MASTER_TECHNOLOGY_ID)');
    create_index_if_missing('IX_QUESTION_CREATED_YEAR_FILTER',
        'CREATE INDEX IX_QUESTION_CREATED_YEAR_FILTER ON QUESTION (CREATED_AT, STATUS, OWNER_ORGANIZATION_ID)');
    create_index_if_missing('IX_CATEGORY_OWNER_STATUS_NAME',
        'CREATE INDEX IX_CATEGORY_OWNER_STATUS_NAME ON QUESTION_CATEGORY (OWNER_ORGANIZATION_ID, STATUS, CATEGORY_NAME)');
END;
/

MERGE INTO APP_PERMISSION target
USING (
    SELECT 'CATALOG_VIEW' code, 'Consultar catálogos' name,
           'CATALOGS' module_code, 'Permite consultar el módulo centralizado de catálogos.' description FROM DUAL UNION ALL
    SELECT 'CATALOG_MANAGE', 'Administrar catálogos',
           'CATALOGS', 'Permite crear, editar, activar, inactivar y eliminar valores sin dependencias.' FROM DUAL
) source
ON (target.PERMISSION_CODE = source.code)
WHEN NOT MATCHED THEN INSERT
    (PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION)
VALUES
    (source.code, source.name, source.module_code, source.description);

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT role.ROLE_ID, permission.PERMISSION_ID
  FROM APP_ROLE role
  JOIN APP_PERMISSION permission
    ON permission.PERMISSION_CODE IN ('CATALOG_VIEW', 'CATALOG_MANAGE')
 WHERE role.ROLE_CODE = 'ADMINISTRATOR'
   AND NOT EXISTS (
       SELECT 1 FROM APP_ROLE_PERMISSION assigned
        WHERE assigned.ROLE_ID = role.ROLE_ID
          AND assigned.PERMISSION_ID = permission.PERMISSION_ID
   );

-- Los permisos anteriores continúan presentes para compatibilidad técnica,
-- pero la administración visual se centraliza en CATALOG_VIEW/CATALOG_MANAGE.
COMMIT;
