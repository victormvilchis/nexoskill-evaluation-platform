MERGE INTO TECHNOLOGICAL_PROFILE_CATALOG target
USING (
    SELECT '00000000-0000-0000-2000-000000000001' PUBLIC_ID,
           'DEVELOPER' PROFILE_CODE, 'Desarrollador' PROFILE_NAME, 10 DISPLAY_ORDER FROM DUAL UNION ALL
    SELECT '00000000-0000-0000-2000-000000000002',
           'FUNCTIONAL', 'Funcional', 20 FROM DUAL UNION ALL
    SELECT '00000000-0000-0000-2000-000000000003',
           'SPECIALIZED_PLATFORM', 'Plataforma especializada', 30 FROM DUAL
) source
ON (target.PROFILE_CODE = source.PROFILE_CODE)
WHEN NOT MATCHED THEN INSERT
    (PUBLIC_ID, PROFILE_CODE, PROFILE_NAME, STATUS, DISPLAY_ORDER, CREATED_AT, UPDATED_AT, VERSION_NO)
VALUES
    (source.PUBLIC_ID, source.PROFILE_CODE, source.PROFILE_NAME, 'ACTIVE', source.DISPLAY_ORDER,
     SYSTIMESTAMP, SYSTIMESTAMP, 0);

-- QUESTION_TECHNOLOGY se convierte en la fuente maestra de tecnologías. Los
-- registros del catálogo de certificaciones se conservan como puente para no
-- romper los perfiles ya capturados.
MERGE INTO QUESTION_TECHNOLOGY target
USING (
    SELECT TECHNOLOGY_CODE,
           MIN(TECHNOLOGY_NAME) TECHNOLOGY_NAME,
           MIN(SORT_ORDER) DISPLAY_ORDER,
           MIN(STATUS) STATUS
      FROM CERTIFICATION_TECHNOLOGY_CATALOG
     GROUP BY TECHNOLOGY_CODE
) source
ON (UPPER(target.TECHNOLOGY_CODE) = UPPER(source.TECHNOLOGY_CODE))
WHEN NOT MATCHED THEN INSERT
    (PUBLIC_ID, TECHNOLOGY_CODE, TECHNOLOGY_NAME, STATUS, DISPLAY_ORDER,
     CREATED_AT, UPDATED_AT, VERSION_NO)
VALUES
    (LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()),
        '(.{8})(.{4})(.{4})(.{4})(.{12})', '\1-\2-\3-\4-\5')),
     UPPER(TRIM(source.TECHNOLOGY_CODE)), source.TECHNOLOGY_NAME,
     CASE WHEN source.STATUS = 'INACTIVE' THEN 'INACTIVE' ELSE 'ACTIVE' END,
     source.DISPLAY_ORDER, SYSTIMESTAMP, SYSTIMESTAMP, 0);

-- Todo valor tecnológico maestro queda disponible para certificaciones mediante
-- un puente compatible con los perfiles existentes. La operación es idempotente.
MERGE INTO CERTIFICATION_TECHNOLOGY_CATALOG target
USING (
    SELECT TECHNOLOGY_ID,
           PUBLIC_ID,
           TECHNOLOGY_CODE,
           TECHNOLOGY_NAME,
           STATUS,
           DISPLAY_ORDER
      FROM QUESTION_TECHNOLOGY
) source
ON (UPPER(target.TECHNOLOGY_CODE) = UPPER(source.TECHNOLOGY_CODE))
WHEN MATCHED THEN UPDATE SET
    target.MASTER_TECHNOLOGY_ID = source.TECHNOLOGY_ID,
    target.TECHNOLOGY_NAME = source.TECHNOLOGY_NAME,
    target.STATUS = source.STATUS,
    target.SORT_ORDER = source.DISPLAY_ORDER,
    target.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
    (PUBLIC_ID, TECHNOLOGY_CODE, TECHNOLOGY_NAME, STATUS, SORT_ORDER,
     CREATED_AT, UPDATED_AT, VERSION_NO, MASTER_TECHNOLOGY_ID)
VALUES
    (LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()),
        '(.{8})(.{4})(.{4})(.{4})(.{12})', '\1-\2-\3-\4-\5')),
     source.TECHNOLOGY_CODE, source.TECHNOLOGY_NAME, source.STATUS,
     source.DISPLAY_ORDER, SYSTIMESTAMP, SYSTIMESTAMP, 0, source.TECHNOLOGY_ID);

