        'ALTER TABLE QUESTION_DIFFICULTY_CATALOG ADD CONSTRAINT FK_QUESTION_DIFF_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID)');
