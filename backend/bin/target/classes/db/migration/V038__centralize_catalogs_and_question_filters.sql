-- Centralización de catálogos reutilizables y soporte para los filtros compactos
-- del Banco de Preguntas. La migración es incremental y conserva todas las
-- relaciones históricas existentes.

DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('QUESTION_TECHNOLOGY', 'DESCRIPTION', 'DESCRIPTION VARCHAR2(500 CHAR)');
    add_column_if_missing('QUESTION_TECHNOLOGY', 'CREATED_BY', 'CREATED_BY NUMBER');
    add_column_if_missing('QUESTION_TECHNOLOGY', 'UPDATED_BY', 'UPDATED_BY NUMBER');

    add_column_if_missing('QUESTION_TYPE_CATALOG', 'DISPLAY_ORDER', 'DISPLAY_ORDER NUMBER DEFAULT 0 NOT NULL');
    add_column_if_missing('QUESTION_TYPE_CATALOG', 'CREATED_BY', 'CREATED_BY NUMBER');
    add_column_if_missing('QUESTION_TYPE_CATALOG', 'UPDATED_BY', 'UPDATED_BY NUMBER');
    add_column_if_missing('QUESTION_TYPE_CATALOG', 'UPDATED_AT', 'UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL');
    add_column_if_missing('QUESTION_TYPE_CATALOG', 'VERSION_NO', 'VERSION_NO NUMBER DEFAULT 0 NOT NULL');

    add_column_if_missing('QUESTION_DIFFICULTY_CATALOG', 'DESCRIPTION', 'DESCRIPTION VARCHAR2(500 CHAR)');
    add_column_if_missing('QUESTION_DIFFICULTY_CATALOG', 'CREATED_BY', 'CREATED_BY NUMBER');
    add_column_if_missing('QUESTION_DIFFICULTY_CATALOG', 'UPDATED_BY', 'UPDATED_BY NUMBER');
    add_column_if_missing('QUESTION_DIFFICULTY_CATALOG', 'UPDATED_AT', 'UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL');
    add_column_if_missing('QUESTION_DIFFICULTY_CATALOG', 'VERSION_NO', 'VERSION_NO NUMBER DEFAULT 0 NOT NULL');

    add_column_if_missing('CERTIFICATION_PROFILE_CATALOG', 'DESCRIPTION', 'DESCRIPTION VARCHAR2(500 CHAR)');
    add_column_if_missing('CERTIFICATION_PROFILE_CATALOG', 'CREATED_BY', 'CREATED_BY NUMBER');
    add_column_if_missing('CERTIFICATION_PROFILE_CATALOG', 'UPDATED_BY', 'UPDATED_BY NUMBER');

    add_column_if_missing('CERTIFICATION_TECHNOLOGY_CATALOG', 'MASTER_TECHNOLOGY_ID', 'MASTER_TECHNOLOGY_ID NUMBER');
END;
/

-- Los estados operativos de los catálogos se homologan a ACTIVE/INACTIVE.
-- Se retiran restricciones rígidas que impedían ampliar perfiles tecnológicos
-- y administrar libremente el orden de las dificultades.
DECLARE
    PROCEDURE drop_constraint_if_exists(p_table VARCHAR2, p_constraint VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_table)
           AND CONSTRAINT_NAME = UPPER(p_constraint);
        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' DROP CONSTRAINT ' || p_constraint;
        END IF;
    END;
BEGIN
    drop_constraint_if_exists('CERTIFICATION_PROFILE_CATALOG', 'CK_CERT_PROFILE_TECH');
    drop_constraint_if_exists('STUDENT_CERTIFICATION_PROFILE', 'CK_STUDENT_CERT_PROFILE_TECH');
    drop_constraint_if_exists('QUESTION_DIFFICULTY_CATALOG', 'UK_QUESTION_DIFFICULTY_ORDER');
END;
/

UPDATE QUESTION_TYPE_CATALOG
   SET DISPLAY_ORDER = CASE TYPE_CODE
       WHEN 'SINGLE_CHOICE' THEN 10
       WHEN 'MULTIPLE_CHOICE' THEN 20
       WHEN 'TRUE_FALSE' THEN 30
       WHEN 'MATCHING' THEN 40
       WHEN 'OPEN_TEXT' THEN 50
       ELSE 100
   END
 WHERE DISPLAY_ORDER = 0;

UPDATE QUESTION_TYPE_CATALOG
   SET UPDATED_AT = NVL(UPDATED_AT, CREATED_AT);

UPDATE QUESTION_DIFFICULTY_CATALOG
   SET UPDATED_AT = NVL(UPDATED_AT, CREATED_AT);

DECLARE
    v_count NUMBER;
BEGIN
