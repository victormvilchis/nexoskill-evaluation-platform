CREATE TABLE APP_USER (
    USER_ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID                VARCHAR2(36 CHAR) NOT NULL,
    EMAIL                    VARCHAR2(254 CHAR) NOT NULL,
    NORMALIZED_EMAIL         VARCHAR2(254 CHAR) NOT NULL,
    PASSWORD_HASH            VARCHAR2(255 CHAR) NOT NULL,
    FIRST_NAME               VARCHAR2(100 CHAR) NOT NULL,
    LAST_NAME                VARCHAR2(150 CHAR) NOT NULL,
    DISPLAY_NAME             VARCHAR2(250 CHAR) NOT NULL,
    STATUS                   VARCHAR2(30 CHAR) NOT NULL,
    FAILED_LOGIN_ATTEMPTS    NUMBER DEFAULT 0 NOT NULL,
    LOCKED_UNTIL             TIMESTAMP WITH TIME ZONE,
    LAST_LOGIN_AT            TIMESTAMP WITH TIME ZONE,
    CREATED_AT               TIMESTAMP WITH TIME ZONE
                             DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT               TIMESTAMP WITH TIME ZONE,
    VERSION_NO               NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT PK_APP_USER PRIMARY KEY (USER_ID),
    CONSTRAINT UK_APP_USER_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_APP_USER_EMAIL UNIQUE (NORMALIZED_EMAIL),
    CONSTRAINT CK_APP_USER_STATUS CHECK (
        STATUS IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'LOCKED', 'DISABLED')
    )
);

CREATE TABLE APP_ROLE (
    ROLE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ROLE_CODE        VARCHAR2(50 CHAR) NOT NULL,
    ROLE_NAME        VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION      VARCHAR2(500 CHAR),
    SYSTEM_ROLE      NUMBER(1) DEFAULT 0 NOT NULL,
    STATUS           VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE
                     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_APP_ROLE PRIMARY KEY (ROLE_ID),
    CONSTRAINT UK_APP_ROLE_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CK_APP_ROLE_SYSTEM CHECK (SYSTEM_ROLE IN (0, 1)),
    CONSTRAINT CK_APP_ROLE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE APP_PERMISSION (
    PERMISSION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PERMISSION_CODE  VARCHAR2(100 CHAR) NOT NULL,
    PERMISSION_NAME  VARCHAR2(150 CHAR) NOT NULL,
    MODULE_CODE      VARCHAR2(50 CHAR) NOT NULL,
    DESCRIPTION      VARCHAR2(500 CHAR),
    CREATED_AT       TIMESTAMP WITH TIME ZONE
                     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_APP_PERMISSION PRIMARY KEY (PERMISSION_ID),
    CONSTRAINT UK_APP_PERMISSION_CODE UNIQUE (PERMISSION_CODE)
);

CREATE TABLE APP_USER_ROLE (
    USER_ID          NUMBER NOT NULL,
    ROLE_ID          NUMBER NOT NULL,
    ASSIGNED_AT      TIMESTAMP WITH TIME ZONE
                     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_APP_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_APP_USER_ROLE_USER
        FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_APP_USER_ROLE_ROLE
        FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLE (ROLE_ID)
);

CREATE TABLE APP_ROLE_PERMISSION (
    ROLE_ID          NUMBER NOT NULL,
    PERMISSION_ID    NUMBER NOT NULL,
    GRANTED_AT       TIMESTAMP WITH TIME ZONE
                     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_APP_ROLE_PERMISSION
        PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERMISSION_ROLE
        FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLE (ROLE_ID),
    CONSTRAINT FK_ROLE_PERMISSION_PERMISSION
        FOREIGN KEY (PERMISSION_ID)
        REFERENCES APP_PERMISSION (PERMISSION_ID)
);

CREATE TABLE AUTH_SESSION (
    SESSION_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID         VARCHAR2(36 CHAR) NOT NULL,
    USER_ID           NUMBER NOT NULL,
    TOKEN_HASH        VARCHAR2(64 CHAR) NOT NULL,
    STATUS            VARCHAR2(30 CHAR) NOT NULL,
    IP_ADDRESS        VARCHAR2(64 CHAR),
    USER_AGENT        VARCHAR2(1000 CHAR),
    CREATED_AT        TIMESTAMP WITH TIME ZONE
                      DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_ACTIVITY_AT  TIMESTAMP WITH TIME ZONE,
    EXPIRES_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED_AT        TIMESTAMP WITH TIME ZONE,

    CONSTRAINT PK_AUTH_SESSION PRIMARY KEY (SESSION_ID),
    CONSTRAINT UK_AUTH_SESSION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_AUTH_SESSION_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_AUTH_SESSION_USER
        FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_AUTH_SESSION_STATUS CHECK (
        STATUS IN ('ACTIVE', 'REVOKED', 'EXPIRED')
    )
);

CREATE TABLE LOGIN_ATTEMPT (
    LOGIN_ATTEMPT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID          NUMBER,
    ATTEMPTED_EMAIL  VARCHAR2(254 CHAR),
    LOGIN_SUCCEEDED       NUMBER(1) NOT NULL,
    FAILURE_REASON   VARCHAR2(100 CHAR),
    IP_ADDRESS       VARCHAR2(64 CHAR),
    USER_AGENT       VARCHAR2(1000 CHAR),
    ATTEMPTED_AT     TIMESTAMP WITH TIME ZONE
                     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_LOGIN_ATTEMPT PRIMARY KEY (LOGIN_ATTEMPT_ID),
    CONSTRAINT FK_LOGIN_ATTEMPT_USER
        FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_LOGIN_ATTEMPT_SUCCESS CHECK (LOGIN_SUCCEEDED IN (0, 1))
);

CREATE TABLE AUDIT_EVENT (
    AUDIT_EVENT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        VARCHAR2(36 CHAR) NOT NULL,
    USER_ID          NUMBER,
    EVENT_TYPE       VARCHAR2(100 CHAR) NOT NULL,
    MODULE_CODE      VARCHAR2(50 CHAR) NOT NULL,
    DESCRIPTION      VARCHAR2(1000 CHAR),
    IP_ADDRESS       VARCHAR2(64 CHAR),
    USER_AGENT       VARCHAR2(1000 CHAR),
    EVENT_DATA       CLOB,
    OCCURRED_AT      TIMESTAMP WITH TIME ZONE
                     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_AUDIT_EVENT PRIMARY KEY (AUDIT_EVENT_ID),
    CONSTRAINT UK_AUDIT_EVENT_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_AUDIT_EVENT_USER
        FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID)
);

