DECLARE
    FUNCTION index_with_columns(p_table VARCHAR2, p_columns VARCHAR2) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM (
                SELECT i.INDEX_NAME,
                       LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION) COLUMN_LIST
                  FROM USER_INDEXES i
                  JOIN USER_IND_COLUMNS c ON c.INDEX_NAME = i.INDEX_NAME
                 WHERE i.TABLE_NAME = UPPER(p_table)
                 GROUP BY i.INDEX_NAME
               )
         WHERE COLUMN_LIST = UPPER(p_columns);
        RETURN v_count;
    END;
BEGIN
    IF index_with_columns('STUDENT', 'RECORD_MODULE,ORGANIZATION_ID,TALENT_TYPE,STATUS') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_TALENT_BANK ON STUDENT (RECORD_MODULE, ORGANIZATION_ID, TALENT_TYPE, STATUS)';
    END IF;
    IF index_with_columns('TALENT_CV_DOCUMENT', 'ORGANIZATION_ID,STUDENT_ID') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_TALENT_CV_ORG_STUDENT ON TALENT_CV_DOCUMENT (ORGANIZATION_ID, STUDENT_ID)';
    END IF;
END;
