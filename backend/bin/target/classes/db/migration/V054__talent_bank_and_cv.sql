-- Talent Bank conserva la misma identidad STUDENT para evitar duplicados y preservar históricos.
-- Los registros existentes permanecen como colaboradores mediante el valor por defecto COLLABORATOR.
DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('STUDENT', 'RECORD_MODULE',
        'RECORD_MODULE VARCHAR2(30 CHAR) DEFAULT ''COLLABORATOR'' NOT NULL');
    add_column_if_missing('STUDENT', 'TALENT_TYPE', 'TALENT_TYPE VARCHAR2(30 CHAR)');
    add_column_if_missing('STUDENT', 'ORGANIZATION_HIRED_ON', 'ORGANIZATION_HIRED_ON DATE');
    add_column_if_missing('STUDENT', 'TALENT_PROFILE_CODE', 'TALENT_PROFILE_CODE VARCHAR2(10 CHAR)');
    add_column_if_missing('STUDENT', 'TALENT_TECHNOLOGY_ID', 'TALENT_TECHNOLOGY_ID NUMBER');
    add_column_if_missing('STUDENT', 'TALENT_MOVED_AT', 'TALENT_MOVED_AT TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('STUDENT', 'TALENT_MOVED_BY', 'TALENT_MOVED_BY NUMBER');
END;
/

UPDATE STUDENT
   SET RECORD_MODULE = 'COLLABORATOR'
 WHERE RECORD_MODULE IS NULL;

DECLARE
    PROCEDURE add_constraint_if_missing(p_name VARCHAR2, p_sql VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = UPPER(p_name);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_sql;
        END IF;
    END;
BEGIN
    add_constraint_if_missing('CK_STUDENT_RECORD_MODULE',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_RECORD_MODULE CHECK (RECORD_MODULE IN (''COLLABORATOR'',''TALENT_BANK''))');
    add_constraint_if_missing('CK_STUDENT_TALENT_TYPE',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_TALENT_TYPE CHECK (TALENT_TYPE IS NULL OR TALENT_TYPE IN (''ACADEMY'',''PROSPECT'',''BBVA_EXIT''))');
    add_constraint_if_missing('CK_STUDENT_TALENT_PROFILE',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_TALENT_PROFILE CHECK (TALENT_PROFILE_CODE IS NULL OR TALENT_PROFILE_CODE IN (''TR'',''JR'',''STD'',''SR''))');
    add_constraint_if_missing('CK_STUDENT_TALENT_MODULE',
        'ALTER TABLE STUDENT ADD CONSTRAINT CK_STUDENT_TALENT_MODULE CHECK ((RECORD_MODULE = ''COLLABORATOR'' AND TALENT_TYPE IS NULL) OR (RECORD_MODULE = ''TALENT_BANK'' AND TALENT_TYPE IS NOT NULL))');
    add_constraint_if_missing('FK_STUDENT_TALENT_TECH',
        'ALTER TABLE STUDENT ADD CONSTRAINT FK_STUDENT_TALENT_TECH FOREIGN KEY (TALENT_TECHNOLOGY_ID) REFERENCES QUESTION_TECHNOLOGY (TECHNOLOGY_ID)');
    add_constraint_if_missing('FK_STUDENT_TALENT_MOVED_BY',
        'ALTER TABLE STUDENT ADD CONSTRAINT FK_STUDENT_TALENT_MOVED_BY FOREIGN KEY (TALENT_MOVED_BY) REFERENCES APP_USER (USER_ID)');
END;
