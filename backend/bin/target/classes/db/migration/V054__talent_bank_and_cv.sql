                UPLOADED_BY NUMBER NOT NULL,
                CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                VERSION_NO NUMBER DEFAULT 0 NOT NULL,
                CONSTRAINT PK_TALENT_CV_DOCUMENT PRIMARY KEY (TALENT_CV_DOCUMENT_ID),
                CONSTRAINT UK_TALENT_CV_STUDENT UNIQUE (STUDENT_ID),
                CONSTRAINT FK_TALENT_CV_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (STUDENT_ID),
