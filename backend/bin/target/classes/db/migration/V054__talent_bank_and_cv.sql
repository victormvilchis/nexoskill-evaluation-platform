DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'TALENT_CV_DOCUMENT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE TALENT_CV_DOCUMENT (
                TALENT_CV_DOCUMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
                PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
                STUDENT_ID NUMBER NOT NULL,
