                CONSTRAINT FK_TALENT_CV_UPLOADED_BY FOREIGN KEY (UPLOADED_BY) REFERENCES APP_USER (USER_ID),
                CONSTRAINT CK_TALENT_CV_EXTENSION CHECK (FILE_EXTENSION IN ('pdf','doc','docx','ppt','pptx')),
                CONSTRAINT CK_TALENT_CV_SIZE CHECK (FILE_SIZE > 0)
            )
        ]';
    ELSE
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'TALENT_CV_DOCUMENT'
           AND COLUMN_NAME IN (
               'TALENT_CV_DOCUMENT_ID', 'PUBLIC_ID', 'STUDENT_ID', 'ORGANIZATION_ID',
               'FILE_NAME', 'CONTENT_TYPE', 'FILE_EXTENSION', 'FILE_SIZE', 'FILE_DATA',
               'UPLOADED_BY', 'CREATED_AT', 'UPDATED_AT', 'VERSION_NO'
           );
        IF v_count <> 13 THEN
            RAISE_APPLICATION_ERROR(-20054,
                'TALENT_CV_DOCUMENT existe parcialmente. Revisa sus columnas antes de ejecutar V054.');
        END IF;
    END IF;
END;
