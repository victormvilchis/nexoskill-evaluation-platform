CREATE TABLE FORM_SECTION (
    SECTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FORM_ID NUMBER NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    SECTION_ORDER NUMBER NOT NULL,
    CONSTRAINT FK_FORM_SECTION_FORM FOREIGN KEY (FORM_ID) REFERENCES EVALUATION_FORM(FORM_ID),
    CONSTRAINT UK_FORM_SECTION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_FORM_SECTION_ORDER UNIQUE (FORM_ID, SECTION_ORDER)
);

CREATE TABLE FORM_QUESTION (
    FORM_QUESTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SECTION_ID NUMBER NOT NULL,
    QUESTION_ID NUMBER NOT NULL,
    QUESTION_ORDER NUMBER NOT NULL,
    POINTS NUMBER(8,2) DEFAULT 1 NOT NULL,
    REQUIRED NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_FORM_QUESTION_SECTION FOREIGN KEY (SECTION_ID) REFERENCES FORM_SECTION(SECTION_ID),
    CONSTRAINT FK_FORM_QUESTION_QUESTION FOREIGN KEY (QUESTION_ID) REFERENCES QUESTION(QUESTION_ID),
    CONSTRAINT UK_FORM_QUESTION UNIQUE (SECTION_ID, QUESTION_ID),
    CONSTRAINT UK_FORM_QUESTION_ORDER UNIQUE (SECTION_ID, QUESTION_ORDER),
    CONSTRAINT CK_FORM_QUESTION_POINTS CHECK (POINTS > 0),
    CONSTRAINT CK_FORM_QUESTION_REQUIRED CHECK (REQUIRED IN (0,1))
);

CREATE TABLE FORM_QUESTION_POOL (
    POOL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SECTION_ID NUMBER NOT NULL,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    SOURCE_TYPE VARCHAR2(20 CHAR) NOT NULL,
    COLLECTION_ID NUMBER,
    CATEGORY_ID NUMBER,
    QUESTION_COUNT NUMBER NOT NULL,
    DIFFICULTY_CODE VARCHAR2(30 CHAR),
    POOL_ORDER NUMBER NOT NULL,
    CONSTRAINT FK_FORM_POOL_SECTION FOREIGN KEY (SECTION_ID) REFERENCES FORM_SECTION(SECTION_ID),
    CONSTRAINT FK_FORM_POOL_COLLECTION FOREIGN KEY (COLLECTION_ID) REFERENCES QUESTION_COLLECTION(COLLECTION_ID),
    CONSTRAINT FK_FORM_POOL_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES QUESTION_CATEGORY(CATEGORY_ID),
    CONSTRAINT UK_FORM_POOL_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT CK_FORM_POOL_SOURCE CHECK (SOURCE_TYPE IN ('COLLECTION','CATEGORY')),
    CONSTRAINT CK_FORM_POOL_COUNT CHECK (QUESTION_COUNT > 0),
    CONSTRAINT CK_FORM_POOL_SOURCE_VALUE CHECK (
      (SOURCE_TYPE='COLLECTION' AND COLLECTION_ID IS NOT NULL AND CATEGORY_ID IS NULL)
      OR (SOURCE_TYPE='CATEGORY' AND CATEGORY_ID IS NOT NULL AND COLLECTION_ID IS NULL)
    )
);
