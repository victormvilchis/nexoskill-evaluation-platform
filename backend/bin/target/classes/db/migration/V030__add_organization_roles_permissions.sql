MERGE INTO APP_ROLE target
USING (SELECT 'MANAGER' code, 'Gestor' name FROM DUAL UNION ALL
       SELECT 'SUPERVISOR', 'Supervisor' FROM DUAL) source
ON (target.ROLE_CODE = source.code)
WHEN NOT MATCHED THEN INSERT (ROLE_CODE, ROLE_NAME, DESCRIPTION, SYSTEM_ROLE, STATUS)
VALUES (source.code, source.name, 'Rol interno multiorganización', 1, 'ACTIVE');

MERGE INTO APP_PERMISSION target
USING (
    SELECT 'ORGANIZATION_VIEW' code, 'Consultar organizaciones' name FROM DUAL UNION ALL
    SELECT 'ORGANIZATION_CREATE', 'Crear organizaciones' FROM DUAL UNION ALL
    SELECT 'ORGANIZATION_UPDATE', 'Modificar organizaciones' FROM DUAL UNION ALL
    SELECT 'ORGANIZATION_STATUS_CHANGE', 'Cambiar estado de organizaciones' FROM DUAL UNION ALL
    SELECT 'ORGANIZATION_LICENSE_VIEW', 'Consultar licenciamiento organizacional' FROM DUAL UNION ALL
    SELECT 'ORGANIZATION_LICENSE_UPDATE', 'Modificar licenciamiento organizacional' FROM DUAL UNION ALL
    SELECT 'TENANT_CONTEXT_SELECT', 'Seleccionar contexto organizacional' FROM DUAL
) source
ON (target.PERMISSION_CODE = source.code)
WHEN NOT MATCHED THEN INSERT (PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION)
VALUES (source.code, source.name, 'ORGANIZATIONS', source.name);

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM APP_ROLE r CROSS JOIN APP_PERMISSION p
WHERE r.ROLE_CODE = 'ADMINISTRATOR'
  AND p.MODULE_CODE = 'ORGANIZATIONS'
  AND NOT EXISTS (SELECT 1 FROM APP_ROLE_PERMISSION rp WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID);

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
FROM APP_ROLE r CROSS JOIN APP_PERMISSION p
WHERE r.ROLE_CODE IN ('MANAGER','SUPERVISOR')
  AND p.PERMISSION_CODE IN ('ORGANIZATION_LICENSE_VIEW')
  AND NOT EXISTS (SELECT 1 FROM APP_ROLE_PERMISSION rp WHERE rp.ROLE_ID = r.ROLE_ID AND rp.PERMISSION_ID = p.PERMISSION_ID);
