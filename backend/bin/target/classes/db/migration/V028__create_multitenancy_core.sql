CREATE TABLE ORGANIZATION (
    ORGANIZATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    ORGANIZATION_CODE VARCHAR2(80 CHAR) NOT NULL,
    ORGANIZATION_NAME VARCHAR2(200 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CONTENT_MODE VARCHAR2(30 CHAR) DEFAULT 'CLEAN' NOT NULL,
    VALID_FROM DATE,
    EXPIRES_ON DATE,
    CREATED_BY NUMBER,
    UPDATED_BY NUMBER,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORGANIZATION PRIMARY KEY (ORGANIZATION_ID),
    CONSTRAINT UK_ORGANIZATION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_ORGANIZATION_CODE UNIQUE (ORGANIZATION_CODE),
    CONSTRAINT CK_ORGANIZATION_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED','EXPIRED','DELETED')),
    CONSTRAINT CK_ORGANIZATION_CONTENT CHECK (CONTENT_MODE IN ('GLOBAL_CATALOG','CLEAN','CUSTOM')),
    CONSTRAINT CK_ORGANIZATION_DATES CHECK (VALID_FROM IS NULL OR EXPIRES_ON IS NULL OR EXPIRES_ON >= VALID_FROM),
    CONSTRAINT FK_ORG_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_ORG_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID)
);

CREATE TABLE ORGANIZATION_LICENSE_POLICY (
    LICENSE_POLICY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_ID NUMBER NOT NULL,
    CONTRACTED_SEATS NUMBER DEFAULT 0 NOT NULL,
    INCLUDED_REPLACEMENTS NUMBER DEFAULT 0 NOT NULL,
    ADDITIONAL_REPLACEMENTS NUMBER DEFAULT 0 NOT NULL,
    STANDARD_RELEASE_HOURS NUMBER DEFAULT 24 NOT NULL,
    EXHAUSTED_RELEASE_DAYS NUMBER DEFAULT 7 NOT NULL,
    CYCLE_STARTS_ON DATE NOT NULL,
    CYCLE_ENDS_ON DATE NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORG_LICENSE_POLICY PRIMARY KEY (LICENSE_POLICY_ID),
    CONSTRAINT UK_ORG_LICENSE_POLICY UNIQUE (ORGANIZATION_ID),
    CONSTRAINT FK_ORG_LICENSE_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT CK_ORG_LICENSE_COUNTS CHECK (CONTRACTED_SEATS >= 0 AND INCLUDED_REPLACEMENTS >= 0 AND ADDITIONAL_REPLACEMENTS >= 0),
    CONSTRAINT CK_ORG_LICENSE_RELEASE CHECK (STANDARD_RELEASE_HOURS > 0 AND EXHAUSTED_RELEASE_DAYS >= 0),
    CONSTRAINT CK_ORG_LICENSE_CYCLE CHECK (CYCLE_ENDS_ON > CYCLE_STARTS_ON),
    CONSTRAINT CK_ORG_LICENSE_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE APP_USER_ORGANIZATION (
    USER_ID NUMBER NOT NULL,
    ORGANIZATION_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    ASSIGNED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ASSIGNED_BY NUMBER,
    CONSTRAINT PK_APP_USER_ORGANIZATION PRIMARY KEY (USER_ID),
    CONSTRAINT FK_UO_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_UO_ORGANIZATION FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT FK_UO_ASSIGNED_BY FOREIGN KEY (ASSIGNED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_UO_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE INDEX IX_ORGANIZATION_STATUS ON ORGANIZATION (STATUS, ORGANIZATION_NAME);
CREATE INDEX IX_UO_ORGANIZATION ON APP_USER_ORGANIZATION (ORGANIZATION_ID, STATUS);
