-- Disponibilidad de preguntas por organizaciones y base de clasificación de estudiantes.
-- La migración es incremental: conserva LEVEL_CODE y TECHNOLOGY_ID como columnas históricas.
DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('QUESTION', 'AVAILABILITY_MODE',
        'AVAILABILITY_MODE VARCHAR2(40 CHAR) DEFAULT ''GLOBAL'' NOT NULL');
    add_column_if_missing('STUDENT', 'PROFESSIONAL_PROFILE_ID', 'PROFESSIONAL_PROFILE_ID NUMBER');
    add_column_if_missing('STUDENT', 'TECHNOLOGICAL_PROFILE_ID', 'TECHNOLOGICAL_PROFILE_ID NUMBER');
    add_column_if_missing('STUDENT', 'TECHNOLOGY_ID', 'TECHNOLOGY_ID NUMBER');
    add_column_if_missing('STUDENT', 'CERTIFICATIONS_ENABLED',
        'CERTIFICATIONS_ENABLED NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('STUDENT', 'CERTIFICATION_ENROLLMENT_DATE', 'CERTIFICATION_ENROLLMENT_DATE DATE');
END;
