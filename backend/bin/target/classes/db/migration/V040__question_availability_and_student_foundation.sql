-- Dificultades definitivas. Se conservan los códigos anteriores como INACTIVE.
MERGE INTO QUESTION_DIFFICULTY_CATALOG target
USING (
    SELECT 'JR' DIFFICULTY_CODE, 'JR' DIFFICULTY_NAME, 10 SORT_ORDER FROM DUAL UNION ALL
    SELECT 'STD', 'STD', 20 FROM DUAL UNION ALL
    SELECT 'SR', 'SR', 30 FROM DUAL
) source
ON (target.DIFFICULTY_CODE = source.DIFFICULTY_CODE)
WHEN MATCHED THEN UPDATE SET
    target.DIFFICULTY_NAME = source.DIFFICULTY_NAME,
    target.SORT_ORDER = source.SORT_ORDER,
    target.STATUS = 'ACTIVE',
    target.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
    (DIFFICULTY_CODE, DIFFICULTY_NAME, SORT_ORDER, STATUS, CREATED_AT, UPDATED_AT, VERSION_NO)
VALUES
    (source.DIFFICULTY_CODE, source.DIFFICULTY_NAME, source.SORT_ORDER, 'ACTIVE', SYSTIMESTAMP, SYSTIMESTAMP, 0);

UPDATE QUESTION
   SET DIFFICULTY_CODE = CASE
       WHEN UPPER(NVL(LEVEL_CODE, '')) = 'JR' THEN 'JR'
       WHEN UPPER(NVL(LEVEL_CODE, '')) = 'STD' THEN 'STD'
       WHEN UPPER(NVL(LEVEL_CODE, '')) = 'SR' THEN 'SR'
       WHEN UPPER(DIFFICULTY_CODE) IN ('BASIC','EASY','BEGINNER','BASICO') THEN 'JR'
       WHEN UPPER(DIFFICULTY_CODE) IN ('INTERMEDIATE','MEDIUM','MEDIUM_LEVEL','INTERMEDIO') THEN 'STD'
       WHEN UPPER(DIFFICULTY_CODE) IN ('ADVANCED','HARD','EXPERT','AVANZADO') THEN 'SR'
       ELSE DIFFICULTY_CODE
   END
 WHERE UPPER(NVL(LEVEL_CODE, DIFFICULTY_CODE)) IN
       ('JR','STD','SR','BASIC','EASY','BEGINNER','BASICO','INTERMEDIATE','MEDIUM','MEDIUM_LEVEL','INTERMEDIO','ADVANCED','HARD','EXPERT','AVANZADO');

UPDATE QUESTION_DIFFICULTY_CATALOG
   SET STATUS = 'INACTIVE', UPDATED_AT = SYSTIMESTAMP
 WHERE DIFFICULTY_CODE NOT IN ('JR','STD','SR')
   AND STATUS = 'ACTIVE';

UPDATE QUESTION SET AVAILABILITY_MODE = 'GLOBAL'
 WHERE CONTENT_SCOPE = 'GLOBAL' AND AVAILABILITY_MODE IS NULL;

COMMIT;
