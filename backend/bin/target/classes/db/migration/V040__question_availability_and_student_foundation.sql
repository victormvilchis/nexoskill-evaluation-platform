        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = UPPER(p_name);
        IF v_count = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
BEGIN
    add_constraint_if_missing('CK_QUESTION_AVAILABILITY_MODE',
        'ALTER TABLE QUESTION ADD CONSTRAINT CK_QUESTION_AVAILABILITY_MODE CHECK (AVAILABILITY_MODE IN (''GLOBAL'',''SELECTED_ORGANIZATIONS''))');
