DECLARE
    PROCEDURE create_index_if_missing(p_name VARCHAR2, p_sql VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = UPPER(p_name);
        IF v_count = 0 THEN
            BEGIN
                EXECUTE IMMEDIATE p_sql;
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE NOT IN (-1408, -955) THEN RAISE; END IF;
            END;
        END IF;
    END;
BEGIN
    create_index_if_missing('IX_QUESTION_ORG_AVAIL_ORG',
        'CREATE INDEX IX_QUESTION_ORG_AVAIL_ORG ON QUESTION_ORGANIZATION_AVAILABILITY (ORGANIZATION_ID, STATUS, QUESTION_ID)');
    create_index_if_missing('IX_STUDENT_FOUNDATION_FILTERS',
        'CREATE INDEX IX_STUDENT_FOUNDATION_FILTERS ON STUDENT (ORGANIZATION_ID, STATUS, PROFESSIONAL_PROFILE_ID, TECHNOLOGICAL_PROFILE_ID, TECHNOLOGY_ID)');
END;
