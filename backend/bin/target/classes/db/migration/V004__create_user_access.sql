CREATE TABLE USER_ACCESS (
    USER_ACCESS_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         NUMBER NOT NULL,
    STARTS_AT       TIMESTAMP WITH TIME ZONE NOT NULL,
    EXPIRES_AT      TIMESTAMP WITH TIME ZONE,
    STATUS          VARCHAR2(30 CHAR) NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE
                    DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE,
    VERSION_NO      NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT PK_USER_ACCESS PRIMARY KEY (USER_ACCESS_ID),
    CONSTRAINT UK_USER_ACCESS_USER UNIQUE (USER_ID),
    CONSTRAINT FK_USER_ACCESS_USER
        FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_USER_ACCESS_STATUS CHECK (
        STATUS IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'EXPIRED', 'CANCELED')
    ),
    CONSTRAINT CK_USER_ACCESS_DATES CHECK (
        EXPIRES_AT IS NULL OR EXPIRES_AT > STARTS_AT
    )
);

CREATE INDEX IX_USER_ACCESS_STATUS
    ON USER_ACCESS (STATUS);

CREATE INDEX IX_USER_ACCESS_EXPIRATION
    ON USER_ACCESS (EXPIRES_AT, STATUS);
