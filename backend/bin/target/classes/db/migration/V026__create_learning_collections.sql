CREATE TABLE LEARNING_COLLECTION (
    COLLECTION_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID           VARCHAR2(36 CHAR) NOT NULL,
    COLLECTION_CODE     VARCHAR2(80 CHAR) NOT NULL,
    COLLECTION_NAME     VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION         VARCHAR2(2000 CHAR),
    STATUS              VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION_NO          NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_LEARNING_COLLECTION PRIMARY KEY (COLLECTION_ID),
    CONSTRAINT UK_LEARNING_COLLECTION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_LEARNING_COLLECTION_CODE UNIQUE (COLLECTION_CODE),
    CONSTRAINT CK_LEARNING_COLLECTION_STATUS CHECK (
        STATUS IN ('DRAFT', 'ACTIVE', 'INACTIVE', 'ARCHIVED')
    )
);

CREATE TABLE LEARNING_COLLECTION_LEVEL (
    LEVEL_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COLLECTION_ID       NUMBER NOT NULL,
    FORM_ID             NUMBER NOT NULL,
    LEVEL_ORDER         NUMBER NOT NULL,
    UNLOCK_RULE         VARCHAR2(30 CHAR) DEFAULT 'PASS_PREVIOUS' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LEARNING_COLLECTION_LEVEL PRIMARY KEY (LEVEL_ID),
    CONSTRAINT FK_LC_LEVEL_COLLECTION FOREIGN KEY (COLLECTION_ID)
        REFERENCES LEARNING_COLLECTION (COLLECTION_ID),
    CONSTRAINT FK_LC_LEVEL_FORM FOREIGN KEY (FORM_ID)
        REFERENCES EVALUATION_FORM (FORM_ID),
    CONSTRAINT UK_LC_LEVEL_ORDER UNIQUE (COLLECTION_ID, LEVEL_ORDER),
    CONSTRAINT UK_LC_LEVEL_FORM UNIQUE (COLLECTION_ID, FORM_ID),
    CONSTRAINT CK_LC_LEVEL_ORDER CHECK (LEVEL_ORDER > 0),
    CONSTRAINT CK_LC_LEVEL_UNLOCK CHECK (
        UNLOCK_RULE IN ('FIRST_AVAILABLE', 'PASS_PREVIOUS')
    )
);

CREATE INDEX IX_LEARNING_COLLECTION_STATUS
    ON LEARNING_COLLECTION (STATUS, COLLECTION_NAME);

CREATE INDEX IX_LC_LEVEL_FORM
    ON LEARNING_COLLECTION_LEVEL (FORM_ID);

COMMENT ON TABLE LEARNING_COLLECTION IS
    'Secuencia reutilizable de formularios organizada por niveles.';

COMMENT ON TABLE LEARNING_COLLECTION_LEVEL IS
    'Relacion ordenada entre una coleccion y sus formularios. El primer nivel queda disponible y los siguientes requieren aprobar el anterior.';
