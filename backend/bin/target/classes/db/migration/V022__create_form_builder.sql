CREATE TABLE EVALUATION_FORM (
    FORM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
    FORM_CODE VARCHAR2(80 CHAR) NOT NULL,
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(2000 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    MODE_CODE VARCHAR2(20 CHAR) DEFAULT 'ASSESSMENT' NOT NULL,
    PASSING_SCORE NUMBER(5,2) DEFAULT 80 NOT NULL,
    MAX_ATTEMPTS NUMBER,
    RETRY_UNTIL_PASSED NUMBER(1) DEFAULT 1 NOT NULL,
    ACCEPT_RESPONSES NUMBER(1) DEFAULT 0 NOT NULL,
    STARTS_AT TIMESTAMP WITH TIME ZONE,
    ENDS_AT TIMESTAMP WITH TIME ZONE,
    DURATION_MINUTES NUMBER,
    SHOW_RESULTS NUMBER(1) DEFAULT 1 NOT NULL,
    SHOW_CORRECT_ANSWERS NUMBER(1) DEFAULT 0 NOT NULL,
    RANDOMIZE_QUESTIONS NUMBER(1) DEFAULT 0 NOT NULL,
    RANDOMIZE_OPTIONS NUMBER(1) DEFAULT 0 NOT NULL,
    SHOW_PROGRESS NUMBER(1) DEFAULT 1 NOT NULL,
    HIDE_QUESTION_NUMBERS NUMBER(1) DEFAULT 0 NOT NULL,
    ALLOW_SAVE_RESUME NUMBER(1) DEFAULT 1 NOT NULL,
    ONE_ACTIVE_ATTEMPT NUMBER(1) DEFAULT 1 NOT NULL,
    THANK_YOU_MESSAGE VARCHAR2(2000 CHAR),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY NUMBER,
    VERSION_NO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT UK_EVALUATION_FORM_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_EVALUATION_FORM_CODE UNIQUE (FORM_CODE),
    CONSTRAINT CK_EVALUATION_FORM_STATUS CHECK (STATUS IN ('DRAFT','ACTIVE','DISABLED','CLOSED','ARCHIVED')),
    CONSTRAINT CK_EVALUATION_FORM_MODE CHECK (MODE_CODE IN ('ASSESSMENT','PRACTICE')),
    CONSTRAINT CK_EVALUATION_FORM_SCORE CHECK (PASSING_SCORE BETWEEN 0 AND 100),
    CONSTRAINT CK_EVALUATION_FORM_BOOL CHECK (
      RETRY_UNTIL_PASSED IN (0,1) AND ACCEPT_RESPONSES IN (0,1) AND SHOW_RESULTS IN (0,1)
      AND SHOW_CORRECT_ANSWERS IN (0,1) AND RANDOMIZE_QUESTIONS IN (0,1)
      AND RANDOMIZE_OPTIONS IN (0,1) AND SHOW_PROGRESS IN (0,1)
      AND HIDE_QUESTION_NUMBERS IN (0,1) AND ALLOW_SAVE_RESUME IN (0,1)
      AND ONE_ACTIVE_ATTEMPT IN (0,1)
    ),
    CONSTRAINT CK_EVALUATION_FORM_DATES CHECK (ENDS_AT IS NULL OR STARTS_AT IS NULL OR ENDS_AT > STARTS_AT),
    CONSTRAINT CK_EVALUATION_FORM_DURATION CHECK (DURATION_MINUTES IS NULL OR DURATION_MINUTES > 0),
    CONSTRAINT CK_EVALUATION_FORM_ATTEMPTS CHECK (MAX_ATTEMPTS IS NULL OR MAX_ATTEMPTS > 0)
);

CREATE INDEX IX_EVALUATION_FORM_STATUS ON EVALUATION_FORM (STATUS);
CREATE INDEX IX_EVALUATION_FORM_WINDOW ON EVALUATION_FORM (STARTS_AT, ENDS_AT);
