CREATE TABLE QUESTION_TYPE_CATALOG (
    TYPE_CODE              VARCHAR2(40 CHAR) NOT NULL,
    TYPE_NAME              VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION            VARCHAR2(500 CHAR),
    SUPPORTS_OPTIONS       NUMBER(1) DEFAULT 1 NOT NULL,
    STATUS                 VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_QUESTION_TYPE_CATALOG PRIMARY KEY (TYPE_CODE),
    CONSTRAINT CK_QUESTION_TYPE_OPTIONS CHECK (SUPPORTS_OPTIONS IN (0, 1)),
    CONSTRAINT CK_QUESTION_TYPE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE QUESTION_DIFFICULTY_CATALOG (
    DIFFICULTY_CODE        VARCHAR2(40 CHAR) NOT NULL,
    DIFFICULTY_NAME        VARCHAR2(100 CHAR) NOT NULL,
    SORT_ORDER             NUMBER NOT NULL,
    STATUS                 VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_QUESTION_DIFFICULTY PRIMARY KEY (DIFFICULTY_CODE),
    CONSTRAINT UK_QUESTION_DIFFICULTY_ORDER UNIQUE (SORT_ORDER),
    CONSTRAINT CK_QUESTION_DIFFICULTY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE QUESTION_CATEGORY (
    CATEGORY_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID              VARCHAR2(36 CHAR) NOT NULL,
    CATEGORY_CODE          VARCHAR2(80 CHAR) NOT NULL,
    CATEGORY_NAME          VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPTION            VARCHAR2(500 CHAR),
    STATUS                 VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY             NUMBER,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMP WITH TIME ZONE,
    VERSION_NO             NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT PK_QUESTION_CATEGORY PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UK_QUESTION_CATEGORY_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_QUESTION_CATEGORY_CODE UNIQUE (CATEGORY_CODE),
    CONSTRAINT FK_QUESTION_CATEGORY_CREATOR
        FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_QUESTION_CATEGORY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE QUESTION_TAG (
    TAG_ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID              VARCHAR2(36 CHAR) NOT NULL,
    TAG_CODE               VARCHAR2(80 CHAR) NOT NULL,
    TAG_NAME               VARCHAR2(120 CHAR) NOT NULL,
    STATUS                 VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY             NUMBER,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_QUESTION_TAG PRIMARY KEY (TAG_ID),
    CONSTRAINT UK_QUESTION_TAG_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_QUESTION_TAG_CODE UNIQUE (TAG_CODE),
    CONSTRAINT FK_QUESTION_TAG_CREATOR
        FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_QUESTION_TAG_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE UNIQUE INDEX UK_QUESTION_CATEGORY_NAME_CI
    ON QUESTION_CATEGORY (UPPER(CATEGORY_NAME));

CREATE INDEX IX_QUESTION_CATEGORY_STATUS_NAME
    ON QUESTION_CATEGORY (STATUS, CATEGORY_NAME);

CREATE UNIQUE INDEX UK_QUESTION_TAG_NAME_CI
    ON QUESTION_TAG (UPPER(TAG_NAME));

CREATE INDEX IX_QUESTION_TAG_STATUS_NAME
    ON QUESTION_TAG (STATUS, TAG_NAME);
