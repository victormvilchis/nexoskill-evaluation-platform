MERGE INTO APP_PERMISSION permission_value
USING (
  SELECT 'PATH_VIEW' CODE, 'Consultar Paths' NAME, 'PATHS' MODULE, 'Permite consultar Paths y su composición.' DESCRIPTION FROM DUAL UNION ALL
  SELECT 'PATH_MANAGE', 'Administrar Paths', 'PATHS', 'Permite crear, editar, cambiar estado, asignar y retirar Paths.' FROM DUAL
) source_value
ON (permission_value.PERMISSION_CODE = source_value.CODE)
WHEN NOT MATCHED THEN
  INSERT (PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION)
  VALUES (source_value.CODE, source_value.NAME, source_value.MODULE, source_value.DESCRIPTION);

MERGE INTO APP_ROLE_PERMISSION role_permission
USING (
  SELECT role_value.ROLE_ID, permission_value.PERMISSION_ID
    FROM APP_ROLE role_value
    CROSS JOIN APP_PERMISSION permission_value
   WHERE role_value.ROLE_CODE = 'ADMINISTRATOR'
     AND permission_value.PERMISSION_CODE IN ('PATH_VIEW','PATH_MANAGE')
) source_value
ON (role_permission.ROLE_ID = source_value.ROLE_ID AND role_permission.PERMISSION_ID = source_value.PERMISSION_ID)
WHEN NOT MATCHED THEN
  INSERT (ROLE_ID, PERMISSION_ID) VALUES (source_value.ROLE_ID, source_value.PERMISSION_ID);

COMMIT;
