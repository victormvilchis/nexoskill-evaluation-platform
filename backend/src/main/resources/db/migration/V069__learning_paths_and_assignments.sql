DECLARE
    FUNCTION index_with_columns(p_table VARCHAR2, p_columns VARCHAR2) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM (
                SELECT i.INDEX_NAME,
                       LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION) COLUMN_LIST
                  FROM USER_INDEXES i
                  JOIN USER_IND_COLUMNS c ON c.INDEX_NAME = i.INDEX_NAME
                 WHERE i.TABLE_NAME = UPPER(p_table)
                 GROUP BY i.INDEX_NAME
               )
         WHERE COLUMN_LIST = UPPER(p_columns);
        RETURN v_count;
    END;
BEGIN
    IF index_with_columns('LEARNING_PATH', 'CONTENT_SCOPE,OWNER_ORGANIZATION_ID,STATUS,PATH_NAME') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_LEARNING_PATH_SCOPE ON LEARNING_PATH (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, STATUS, PATH_NAME)';
    END IF;
    IF index_with_columns('LEARNING_PATH_COLLECTION', 'PATH_ID,COLLECTION_ORDER') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_PATH_COLLECTION_ORDER ON LEARNING_PATH_COLLECTION (PATH_ID, COLLECTION_ORDER)';
    END IF;
    IF index_with_columns('STUDENT_PATH_ASSIGNMENT', 'ORGANIZATION_ID,STUDENT_ID,STATUS,ASSIGNED_AT') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_PATH_OWNER ON STUDENT_PATH_ASSIGNMENT (ORGANIZATION_ID, STUDENT_ID, STATUS, ASSIGNED_AT)';
    END IF;
    IF index_with_columns('STUDENT_FORM_ASSIGNMENT_ORIGIN', 'PATH_ASSIGNMENT_ID,STATUS') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_FORM_ASSIGN_ORIGIN_PATH ON STUDENT_FORM_ASSIGNMENT_ORIGIN (PATH_ASSIGNMENT_ID, STATUS)';
    END IF;
    IF index_with_columns('STUDENT_FORM_ASSIGNMENT_ORIGIN', 'FORM_ASSIGNMENT_ID,STATUS') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_FORM_ASSIGN_ORIGIN_FORM ON STUDENT_FORM_ASSIGNMENT_ORIGIN (FORM_ASSIGNMENT_ID, STATUS)';
    END IF;
END;
