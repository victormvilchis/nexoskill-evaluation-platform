-- Paths: composición de Colecciones y asignación segura a colaboradores.
-- No duplica Colecciones, Formularios ni Preguntas. Las evaluaciones derivadas de Paths
-- reutilizan STUDENT_FORM_ASSIGNMENT y registran únicamente el origen de disponibilidad.

DECLARE
    PROCEDURE create_table_if_missing(p_table VARCHAR2, p_sql CLOB) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = UPPER(p_table);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_sql;
        END IF;
    END;

    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_definition VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table)
           AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_column || ' ' || p_definition || ')';
        END IF;
    END;
BEGIN
    create_table_if_missing('LEARNING_PATH', q'[
        CREATE TABLE LEARNING_PATH (
            PATH_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
            PATH_CODE VARCHAR2(100 CHAR) NOT NULL,
            PATH_NAME VARCHAR2(200 CHAR) NOT NULL,
            NORMALIZED_NAME VARCHAR2(200 CHAR) GENERATED ALWAYS AS (UPPER(TRIM(PATH_NAME))) VIRTUAL,
            DESCRIPTION VARCHAR2(2000 CHAR),
            STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
            CONTENT_SCOPE VARCHAR2(20 CHAR) NOT NULL,
            OWNER_ORGANIZATION_ID NUMBER NOT NULL,
            CREATED_BY NUMBER NOT NULL,
            UPDATED_BY NUMBER NOT NULL,
            CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            VERSION_NO NUMBER DEFAULT 0 NOT NULL,
            CONSTRAINT PK_LEARNING_PATH PRIMARY KEY (PATH_ID),
            CONSTRAINT UK_LEARNING_PATH_PUBLIC UNIQUE (PUBLIC_ID),
            CONSTRAINT UK_LEARNING_PATH_CODE UNIQUE (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, PATH_CODE),
            CONSTRAINT UK_LEARNING_PATH_NAME UNIQUE (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, NORMALIZED_NAME),
            CONSTRAINT FK_LEARNING_PATH_OWNER FOREIGN KEY (OWNER_ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
            CONSTRAINT FK_LEARNING_PATH_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
            CONSTRAINT FK_LEARNING_PATH_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID),
            CONSTRAINT CK_LEARNING_PATH_STATUS CHECK (STATUS IN ('DRAFT','ACTIVE','INACTIVE','ARCHIVED')),
            CONSTRAINT CK_LEARNING_PATH_SCOPE CHECK (CONTENT_SCOPE IN ('GLOBAL','ORGANIZATION'))
        )
    ]');

    create_table_if_missing('LEARNING_PATH_COLLECTION', q'[
        CREATE TABLE LEARNING_PATH_COLLECTION (
            PATH_COLLECTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            PATH_ID NUMBER NOT NULL,
            COLLECTION_ID NUMBER NOT NULL,
            COLLECTION_ORDER NUMBER NOT NULL,
            CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_LEARNING_PATH_COLLECTION PRIMARY KEY (PATH_COLLECTION_ID),
            CONSTRAINT FK_PATH_COLLECTION_PATH FOREIGN KEY (PATH_ID) REFERENCES LEARNING_PATH (PATH_ID),
            CONSTRAINT FK_PATH_COLLECTION_COLLECTION FOREIGN KEY (COLLECTION_ID) REFERENCES LEARNING_COLLECTION (COLLECTION_ID),
            CONSTRAINT UK_PATH_COLLECTION UNIQUE (PATH_ID, COLLECTION_ID),
            CONSTRAINT UK_PATH_COLLECTION_ORDER UNIQUE (PATH_ID, COLLECTION_ORDER),
            CONSTRAINT CK_PATH_COLLECTION_ORDER CHECK (COLLECTION_ORDER > 0)
        )
    ]');

    create_table_if_missing('STUDENT_PATH_ASSIGNMENT', q'[
        CREATE TABLE STUDENT_PATH_ASSIGNMENT (
            PATH_ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
            STUDENT_ID NUMBER NOT NULL,
            ORGANIZATION_ID NUMBER NOT NULL,
            PATH_ID NUMBER NOT NULL,
            STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
            ACTIVE_PATH_ID NUMBER GENERATED ALWAYS AS (CASE WHEN STATUS = 'ACTIVE' THEN PATH_ID ELSE NULL END) VIRTUAL,
            ASSIGNED_BY NUMBER NOT NULL,
            ASSIGNED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            REMOVED_BY NUMBER,
            REMOVED_AT TIMESTAMP WITH TIME ZONE,
            UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            VERSION_NO NUMBER DEFAULT 0 NOT NULL,
            CONSTRAINT PK_STUDENT_PATH_ASSIGN PRIMARY KEY (PATH_ASSIGNMENT_ID),
            CONSTRAINT UK_STUDENT_PATH_ASSIGN_PUBLIC UNIQUE (PUBLIC_ID),
            CONSTRAINT UK_STUDENT_PATH_ASSIGN_ACTIVE UNIQUE (STUDENT_ID, ACTIVE_PATH_ID),
            CONSTRAINT FK_STUDENT_PATH_ASSIGN_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (STUDENT_ID),
            CONSTRAINT FK_STUDENT_PATH_ASSIGN_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
            CONSTRAINT FK_STUDENT_PATH_ASSIGN_PATH FOREIGN KEY (PATH_ID) REFERENCES LEARNING_PATH (PATH_ID),
            CONSTRAINT FK_STUDENT_PATH_ASSIGN_BY FOREIGN KEY (ASSIGNED_BY) REFERENCES APP_USER (USER_ID),
            CONSTRAINT FK_STUDENT_PATH_REMOVE_BY FOREIGN KEY (REMOVED_BY) REFERENCES APP_USER (USER_ID),
            CONSTRAINT CK_STUDENT_PATH_ASSIGN_STATUS CHECK (STATUS IN ('ACTIVE','REMOVED'))
        )
    ]');

    create_table_if_missing('STUDENT_FORM_ASSIGNMENT_ORIGIN', q'[
        CREATE TABLE STUDENT_FORM_ASSIGNMENT_ORIGIN (
            FORM_ASSIGNMENT_ORIGIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
            PATH_ASSIGNMENT_ID NUMBER NOT NULL,
            FORM_ASSIGNMENT_ID NUMBER NOT NULL,
            STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
            ACTIVE_PATH_ASSIGNMENT_ID NUMBER GENERATED ALWAYS AS
                (CASE WHEN STATUS = 'ACTIVE' THEN PATH_ASSIGNMENT_ID ELSE NULL END) VIRTUAL,
            ACTIVE_FORM_ASSIGNMENT_ID NUMBER GENERATED ALWAYS AS
                (CASE WHEN STATUS = 'ACTIVE' THEN FORM_ASSIGNMENT_ID ELSE NULL END) VIRTUAL,
            CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            REMOVED_AT TIMESTAMP WITH TIME ZONE,
            CONSTRAINT PK_STUDENT_FORM_ASSIGN_ORIGIN PRIMARY KEY (FORM_ASSIGNMENT_ORIGIN_ID),
            CONSTRAINT FK_FORM_ASSIGN_ORIGIN_PATH FOREIGN KEY (PATH_ASSIGNMENT_ID)
                REFERENCES STUDENT_PATH_ASSIGNMENT (PATH_ASSIGNMENT_ID),
            CONSTRAINT FK_FORM_ASSIGN_ORIGIN_FORM FOREIGN KEY (FORM_ASSIGNMENT_ID)
                REFERENCES STUDENT_FORM_ASSIGNMENT (FORM_ASSIGNMENT_ID),
            CONSTRAINT UK_FORM_ASSIGN_ORIGIN_ACTIVE UNIQUE (ACTIVE_PATH_ASSIGNMENT_ID, ACTIVE_FORM_ASSIGNMENT_ID),
            CONSTRAINT CK_FORM_ASSIGN_ORIGIN_STATUS CHECK (STATUS IN ('ACTIVE','REMOVED'))
        )
    ]');

    add_column_if_missing('STUDENT_FORM_ASSIGNMENT', 'DIRECT_SOURCE', 'NUMBER(1) DEFAULT 1 NOT NULL');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'STUDENT_FORM_ASSIGNMENT'
       AND CONSTRAINT_NAME = 'CK_STUDENT_FORM_ASSIGN_DIRECT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE STUDENT_FORM_ASSIGNMENT ADD CONSTRAINT CK_STUDENT_FORM_ASSIGN_DIRECT CHECK (DIRECT_SOURCE IN (0,1))';
    END IF;
END;
