-- Foco ejecutivo de certificaciones derivado en tiempo real e identidad visual por organización.
-- El status no se persiste: la vista se recalcula a partir de ciclos, intentos y aplicabilidad vigentes.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'ORGANIZATION_BRANDING';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE ORGANIZATION_BRANDING (
                ORGANIZATION_ID NUMBER NOT NULL,
                LOGO_CONTENT BLOB,
                LOGO_CONTENT_TYPE VARCHAR2(100 CHAR),
                LOGO_FILE_NAME VARCHAR2(255 CHAR),
                LOGO_UPDATED_AT TIMESTAMP WITH TIME ZONE,
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                VERSION_NO NUMBER DEFAULT 0 NOT NULL,
                CONSTRAINT PK_ORGANIZATION_BRANDING PRIMARY KEY (ORGANIZATION_ID),
                CONSTRAINT FK_ORG_BRANDING_ORG FOREIGN KEY (ORGANIZATION_ID)
                    REFERENCES ORGANIZATION (ORGANIZATION_ID),
                CONSTRAINT CK_ORG_BRANDING_CONTENT CHECK (
                    (LOGO_CONTENT IS NULL AND LOGO_CONTENT_TYPE IS NULL AND LOGO_FILE_NAME IS NULL)
                    OR
                    (LOGO_CONTENT IS NOT NULL AND LOGO_CONTENT_TYPE IS NOT NULL AND LOGO_FILE_NAME IS NOT NULL)
                )
            )
        ]';
    END IF;
END;
/

CREATE OR REPLACE VIEW VW_STUDENT_CERTIFICATION_FOCUS AS
WITH second_attempt AS (
    SELECT a.STUDENT_CERTIFICATION_CYCLE_ID,
           MAX(CASE
               WHEN a.ATTEMPT_NUMBER = 2
                AND (a.APPROVED = 0 OR a.EXAM_STATUS IN ('FAILED','ABSENT'))
               THEN 1 ELSE 0
           END) SECOND_ATTEMPT_FAILED
      FROM STUDENT_CERTIFICATION_CYCLE_ATTEMPT a
     GROUP BY a.STUDENT_CERTIFICATION_CYCLE_ID
),
applicable_cycles AS (
    SELECT c.STUDENT_ID,
           c.ORGANIZATION_ID,
           c.CERTIFICATION_TYPE,
           c.EXPIRATION_DATE,
           c.VALIDITY_STATUS,
           CASE
             WHEN NVL(sa.SECOND_ATTEMPT_FAILED, 0) = 1 THEN 1
             WHEN NVL(c.IMPORTED_FAILURE_COUNT, 0) >= 2
              AND (c.TRACKING_STATUS = 'NOT_APPROVED' OR c.LATEST_EXAM_STATUS = 'FAILED' OR c.APPROVED = 0)
             THEN 1
             ELSE 0
           END SECOND_ATTEMPT_FAILED,
           CASE
             WHEN c.APPROVED = 1
               OR c.LAST_APPROVED_APPLICATION_DATE IS NOT NULL
               OR c.TRACKING_STATUS = 'APPROVED'
               OR c.LATEST_EXAM_STATUS = 'PASSED'
             THEN 1 ELSE 0
           END HAS_APPROVED_HISTORY
      FROM STUDENT_CERTIFICATION_CYCLE c
      JOIN STUDENT s ON s.STUDENT_ID = c.STUDENT_ID AND s.ORGANIZATION_ID = c.ORGANIZATION_ID
      JOIN ORGANIZATION o ON o.ORGANIZATION_ID = s.ORGANIZATION_ID
      LEFT JOIN second_attempt sa
        ON sa.STUDENT_CERTIFICATION_CYCLE_ID = c.STUDENT_CERTIFICATION_CYCLE_ID
     WHERE c.ACTIVE = 1
       AND s.RECORD_MODULE = 'COLLABORATOR'
       AND s.STATUS <> 'DELETED'
       AND o.APPLIES_CERTIFICATIONS = 1
       AND (
            (c.CERTIFICATION_TYPE = 'TECHNOLOGICAL' AND s.APPLIES_TECH_CERT = 1)
         OR (c.CERTIFICATION_TYPE = 'DEVELOPMENT_SECURITY' AND s.APPLIES_DEV_SECURITY = 1)
         OR (c.CERTIFICATION_TYPE = 'NORMATIVE_TESTING' AND s.APPLIES_NORMATIVE_TESTING = 1)
         OR (c.CERTIFICATION_TYPE = 'ONE' AND s.APPLIES_ONE = 1)
         OR (c.CERTIFICATION_TYPE = 'AGILE' AND s.APPLIES_AGILE = 1)
         OR (c.CERTIFICATION_TYPE = 'JIRA' AND s.APPLIES_JIRA = 1)
       )
),
area_rollup AS (
    SELECT STUDENT_ID,
           ORGANIZATION_ID,
           CERTIFICATION_TYPE,
           MAX(SECOND_ATTEMPT_FAILED) SECOND_ATTEMPT_FAILED,
           MAX(CASE WHEN HAS_APPROVED_HISTORY = 1 AND VALIDITY_STATUS = 'VALID' THEN 1 ELSE 0 END) HAS_VALID,
           MAX(CASE WHEN HAS_APPROVED_HISTORY = 1 AND VALIDITY_STATUS = 'EXPIRING_SOON' THEN 1 ELSE 0 END) HAS_EXPIRING,
           MAX(CASE WHEN HAS_APPROVED_HISTORY = 1 AND VALIDITY_STATUS = 'EXPIRED' THEN 1 ELSE 0 END) HAS_EXPIRED,
           MIN(CASE WHEN HAS_APPROVED_HISTORY = 1 AND VALIDITY_STATUS = 'VALID' THEN EXPIRATION_DATE END) VALID_EXPIRATION_DATE,
           MIN(CASE WHEN HAS_APPROVED_HISTORY = 1 AND VALIDITY_STATUS = 'EXPIRING_SOON' THEN EXPIRATION_DATE END) EXPIRING_EXPIRATION_DATE,
           MAX(CASE WHEN HAS_APPROVED_HISTORY = 1 AND VALIDITY_STATUS = 'EXPIRED' THEN EXPIRATION_DATE END) EXPIRED_EXPIRATION_DATE
      FROM applicable_cycles
     GROUP BY STUDENT_ID, ORGANIZATION_ID, CERTIFICATION_TYPE
),
area_focus AS (
    SELECT STUDENT_ID,
           ORGANIZATION_ID,
           CERTIFICATION_TYPE,
           CASE
             WHEN SECOND_ATTEMPT_FAILED = 1 THEN COALESCE(EXPIRED_EXPIRATION_DATE, EXPIRING_EXPIRATION_DATE, VALID_EXPIRATION_DATE)
             WHEN HAS_VALID = 0 AND HAS_EXPIRING = 0 AND HAS_EXPIRED = 1 THEN EXPIRED_EXPIRATION_DATE
             WHEN HAS_EXPIRING = 1 THEN EXPIRING_EXPIRATION_DATE
             ELSE VALID_EXPIRATION_DATE
           END RELEVANT_EXPIRATION_DATE,
           SECOND_ATTEMPT_FAILED,
           CASE
             WHEN SECOND_ATTEMPT_FAILED = 1 THEN 4
             WHEN HAS_VALID = 0 AND HAS_EXPIRING = 0 AND HAS_EXPIRED = 1 THEN 3
             WHEN HAS_EXPIRING = 1 THEN 2
             ELSE 1
           END FOCUS_RANK
      FROM area_rollup
),
ranked_focus AS (
    SELECT af.*,
           ROW_NUMBER() OVER (
               PARTITION BY af.STUDENT_ID, af.ORGANIZATION_ID
               ORDER BY af.FOCUS_RANK DESC,
                        af.RELEVANT_EXPIRATION_DATE NULLS LAST,
                        af.CERTIFICATION_TYPE
           ) RN
      FROM area_focus af
)
SELECT s.STUDENT_ID,
       s.ORGANIZATION_ID,
       CASE
         WHEN o.APPLIES_CERTIFICATIONS = 0 THEN NULL
         WHEN NVL(rf.FOCUS_RANK, 1) = 4 THEN 'PENDING_DEACTIVATION'
         WHEN NVL(rf.FOCUS_RANK, 1) = 3 THEN 'EXPIRED'
         WHEN NVL(rf.FOCUS_RANK, 1) = 2 THEN 'EXPIRING_SOON'
         ELSE 'IN_RULE'
       END FOCUS_STATUS,
       CASE WHEN o.APPLIES_CERTIFICATIONS = 0 THEN 0 ELSE NVL(rf.FOCUS_RANK, 1) END FOCUS_RANK,
       rf.CERTIFICATION_TYPE TRIGGER_CERTIFICATION_TYPE,
       rf.RELEVANT_EXPIRATION_DATE,
       NVL(rf.SECOND_ATTEMPT_FAILED, 0) SECOND_ATTEMPT_FAILED
  FROM STUDENT s
  JOIN ORGANIZATION o ON o.ORGANIZATION_ID = s.ORGANIZATION_ID
  LEFT JOIN ranked_focus rf
    ON rf.STUDENT_ID = s.STUDENT_ID
   AND rf.ORGANIZATION_ID = s.ORGANIZATION_ID
   AND rf.RN = 1
 WHERE s.RECORD_MODULE = 'COLLABORATOR'
   AND s.STATUS <> 'DELETED';
