CREATE TABLE QUESTION (
    QUESTION_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID              VARCHAR2(36 CHAR) NOT NULL,
    TYPE_CODE              VARCHAR2(40 CHAR) NOT NULL,
    DIFFICULTY_CODE        VARCHAR2(40 CHAR) NOT NULL,
    CATEGORY_ID            NUMBER NOT NULL,
    STATUS                 VARCHAR2(30 CHAR) DEFAULT 'DRAFT' NOT NULL,
    CURRENT_VERSION_ID     NUMBER,
    CREATED_BY             NUMBER NOT NULL,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY             NUMBER,
    UPDATED_AT             TIMESTAMP WITH TIME ZONE,
    VERSION_NO             NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT PK_QUESTION PRIMARY KEY (QUESTION_ID),
    CONSTRAINT UK_QUESTION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_QUESTION_TYPE
        FOREIGN KEY (TYPE_CODE) REFERENCES QUESTION_TYPE_CATALOG (TYPE_CODE),
    CONSTRAINT FK_QUESTION_DIFFICULTY
        FOREIGN KEY (DIFFICULTY_CODE)
        REFERENCES QUESTION_DIFFICULTY_CATALOG (DIFFICULTY_CODE),
    CONSTRAINT FK_QUESTION_CATEGORY
        FOREIGN KEY (CATEGORY_ID) REFERENCES QUESTION_CATEGORY (CATEGORY_ID),
    CONSTRAINT FK_QUESTION_CREATOR
        FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_QUESTION_UPDATER
        FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_QUESTION_STATUS CHECK (
        STATUS IN ('DRAFT', 'UNDER_REVIEW', 'APPROVED', 'PUBLISHED', 'ARCHIVED')
    )
);

CREATE TABLE QUESTION_VERSION (
    QUESTION_VERSION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    QUESTION_ID            NUMBER NOT NULL,
    VERSION_NUMBER         NUMBER NOT NULL,
    STATEMENT_TEXT         CLOB NOT NULL,
    EXPLANATION_TEXT       CLOB,
    CREATED_BY             NUMBER NOT NULL,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_QUESTION_VERSION PRIMARY KEY (QUESTION_VERSION_ID),
    CONSTRAINT UK_QUESTION_VERSION UNIQUE (QUESTION_ID, VERSION_NUMBER),
    CONSTRAINT FK_QUESTION_VERSION_QUESTION
        FOREIGN KEY (QUESTION_ID) REFERENCES QUESTION (QUESTION_ID),
    CONSTRAINT FK_QUESTION_VERSION_CREATOR
        FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID)
);

CREATE TABLE QUESTION_OPTION (
    QUESTION_OPTION_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID              VARCHAR2(36 CHAR) NOT NULL,
    QUESTION_VERSION_ID    NUMBER NOT NULL,
    OPTION_ORDER           NUMBER NOT NULL,
    OPTION_TEXT            CLOB NOT NULL,
    IS_CORRECT             NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_QUESTION_OPTION PRIMARY KEY (QUESTION_OPTION_ID),
    CONSTRAINT UK_QUESTION_OPTION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_QUESTION_OPTION_ORDER
        UNIQUE (QUESTION_VERSION_ID, OPTION_ORDER),
    CONSTRAINT FK_QUESTION_OPTION_VERSION
        FOREIGN KEY (QUESTION_VERSION_ID)
        REFERENCES QUESTION_VERSION (QUESTION_VERSION_ID),
    CONSTRAINT CK_QUESTION_OPTION_CORRECT CHECK (IS_CORRECT IN (0, 1))
);

CREATE TABLE QUESTION_TAG_RELATION (
    QUESTION_ID            NUMBER NOT NULL,
    TAG_ID                 NUMBER NOT NULL,
    ASSIGNED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_QUESTION_TAG_RELATION PRIMARY KEY (QUESTION_ID, TAG_ID),
    CONSTRAINT FK_QUESTION_TAG_REL_QUESTION
        FOREIGN KEY (QUESTION_ID) REFERENCES QUESTION (QUESTION_ID),
    CONSTRAINT FK_QUESTION_TAG_REL_TAG
        FOREIGN KEY (TAG_ID) REFERENCES QUESTION_TAG (TAG_ID)
);

ALTER TABLE QUESTION ADD CONSTRAINT FK_QUESTION_CURRENT_VERSION
    FOREIGN KEY (CURRENT_VERSION_ID)
    REFERENCES QUESTION_VERSION (QUESTION_VERSION_ID);

CREATE INDEX IX_QUESTION_FILTERS
    ON QUESTION (STATUS, TYPE_CODE, DIFFICULTY_CODE, CATEGORY_ID);

CREATE INDEX IX_QUESTION_CREATED_AT
    ON QUESTION (CREATED_AT DESC);

CREATE INDEX IX_QUESTION_VERSION_QUESTION
    ON QUESTION_VERSION (QUESTION_ID, VERSION_NUMBER DESC);
