-- Reutilización idempotente de decisiones sobre actualizaciones de colaboradores.
-- Conserva únicamente la firma exacta del escenario y la acción aplicada.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'STUDENT_IMPORT_CHANGE_DECISION';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STUDENT_IMPORT_CHANGE_DECISION (
                STUDENT_IMPORT_CHANGE_DECISION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
                PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
                ORGANIZATION_ID NUMBER NOT NULL,
                STUDENT_ID NUMBER NOT NULL,
                FIELD_KEY VARCHAR2(180 CHAR) NOT NULL,
                CHANGE_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
                ACTION_CODE VARCHAR2(20 CHAR) NOT NULL,
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT PK_STU_IMP_CH_DEC PRIMARY KEY (STUDENT_IMPORT_CHANGE_DECISION_ID),
                CONSTRAINT UK_STU_IMP_CH_PUBLIC UNIQUE (PUBLIC_ID),
                CONSTRAINT UK_STU_IMP_CH_EXACT UNIQUE (
                    ORGANIZATION_ID, STUDENT_ID, FIELD_KEY, CHANGE_FINGERPRINT
                ),
                CONSTRAINT FK_STU_IMP_CH_ORG FOREIGN KEY (ORGANIZATION_ID)
                    REFERENCES ORGANIZATION (ORGANIZATION_ID),
                CONSTRAINT FK_STU_IMP_CH_STUDENT FOREIGN KEY (STUDENT_ID)
                    REFERENCES STUDENT (STUDENT_ID),
                CONSTRAINT CK_STU_IMP_CH_ACTION CHECK (ACTION_CODE IN (
                    'KEEP_PLATFORM', 'APPLY_EXCEL'
                ))
            )
        ]';
    ELSE
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'STUDENT_IMPORT_CHANGE_DECISION'
           AND COLUMN_NAME IN (
               'STUDENT_IMPORT_CHANGE_DECISION_ID', 'PUBLIC_ID', 'ORGANIZATION_ID',
               'STUDENT_ID', 'FIELD_KEY', 'CHANGE_FINGERPRINT', 'ACTION_CODE', 'UPDATED_AT'
           );
        IF v_count <> 8 THEN
            RAISE_APPLICATION_ERROR(-20063,
                'STUDENT_IMPORT_CHANGE_DECISION existe parcialmente. Revisa sus columnas antes de reintentar V063.');
        END IF;
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM (
          SELECT i.INDEX_NAME,
                 LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION) COLUMN_LIST
            FROM USER_INDEXES i
            JOIN USER_IND_COLUMNS c ON c.INDEX_NAME = i.INDEX_NAME
           WHERE i.TABLE_NAME = 'STUDENT_IMPORT_CHANGE_DECISION'
           GROUP BY i.INDEX_NAME
      )
     WHERE COLUMN_LIST = 'ORGANIZATION_ID,STUDENT_ID,FIELD_KEY';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STU_IMP_CH_LOOKUP ON STUDENT_IMPORT_CHANGE_DECISION (ORGANIZATION_ID, STUDENT_ID, FIELD_KEY)';
    END IF;
END;
