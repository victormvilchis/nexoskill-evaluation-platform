ALTER TABLE ORGANIZATION ADD (
    ORGANIZATION_TYPE VARCHAR2(20 CHAR) DEFAULT 'CUSTOMER' NOT NULL
);

UPDATE ORGANIZATION
SET ORGANIZATION_TYPE = 'CUSTOMER'
WHERE ORGANIZATION_TYPE IS NULL;

UPDATE ORGANIZATION
SET VALID_FROM = TRUNC(CAST(CREATED_AT AS DATE))
WHERE VALID_FROM IS NULL;

ALTER TABLE ORGANIZATION MODIFY (VALID_FROM NOT NULL);
ALTER TABLE ORGANIZATION ADD CONSTRAINT CK_ORGANIZATION_TYPE
    CHECK (ORGANIZATION_TYPE IN ('GLOBAL', 'CUSTOMER'));

MERGE INTO ORGANIZATION target
USING (
    SELECT '00000000-0000-0000-0000-000000000001' public_id,
           'GLOBAL' organization_code,
           'GLOBAL' organization_name
    FROM dual
) source
ON (target.ORGANIZATION_CODE = source.organization_code)
WHEN MATCHED THEN UPDATE SET
    target.PUBLIC_ID = source.public_id,
    target.ORGANIZATION_NAME = source.organization_name,
    target.ORGANIZATION_TYPE = 'GLOBAL',
    target.STATUS = 'ACTIVE',
    target.CONTENT_MODE = 'GLOBAL_CATALOG',
    target.EXPIRES_ON = NULL,
    target.VALID_FROM = DATE '2000-01-01',
    target.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    PUBLIC_ID, ORGANIZATION_CODE, ORGANIZATION_NAME, ORGANIZATION_TYPE,
    STATUS, CONTENT_MODE, VALID_FROM, EXPIRES_ON, CREATED_AT, UPDATED_AT, VERSION_NO
) VALUES (
    source.public_id, source.organization_code, source.organization_name, 'GLOBAL',
    'ACTIVE', 'GLOBAL_CATALOG', DATE '2000-01-01', NULL, SYSTIMESTAMP, SYSTIMESTAMP, 0
);

DELETE FROM ORGANIZATION_LICENSE_POLICY
WHERE ORGANIZATION_ID = (
    SELECT ORGANIZATION_ID FROM ORGANIZATION WHERE ORGANIZATION_TYPE = 'GLOBAL'
);

MERGE INTO APP_USER_ORGANIZATION target
USING (
    SELECT DISTINCT u.USER_ID,
           g.ORGANIZATION_ID,
           SYSTIMESTAMP ASSIGNED_AT
    FROM APP_USER u
    JOIN APP_USER_ROLE ur ON ur.USER_ID = u.USER_ID
    JOIN APP_ROLE r ON r.ROLE_ID = ur.ROLE_ID AND r.ROLE_CODE = 'ADMINISTRATOR'
    CROSS JOIN ORGANIZATION g
    WHERE g.ORGANIZATION_TYPE = 'GLOBAL'
) source
ON (target.USER_ID = source.USER_ID)
WHEN MATCHED THEN UPDATE SET
    target.ORGANIZATION_ID = source.ORGANIZATION_ID,
    target.STATUS = 'ACTIVE',
    target.ASSIGNED_AT = source.ASSIGNED_AT
WHEN NOT MATCHED THEN INSERT (
    USER_ID, ORGANIZATION_ID, STATUS, ASSIGNED_AT, ASSIGNED_BY
) VALUES (
    source.USER_ID, source.ORGANIZATION_ID, 'ACTIVE', source.ASSIGNED_AT, NULL
);

-- Los Gestores y Supervisores legados sin organización quedan inactivos hasta que un Administrador los regularice.
-- El cambio se audita antes de modificar el estado y sus sesiones activas se revocan en la misma migración.
INSERT INTO INTERNAL_USER_STATUS_HISTORY (
    USER_ID, ACTOR_USER_ID, PREVIOUS_STATUS, NEW_STATUS, REASON, OCCURRED_AT
)
SELECT u.USER_ID,
       NULL,
       u.STATUS,
       'INACTIVE',
       'Usuario organizacional sin organización comercial; requiere regularización administrativa',
       SYSTIMESTAMP
FROM APP_USER u
WHERE u.STATUS NOT IN ('INACTIVE', 'DELETED')
  AND EXISTS (
      SELECT 1
      FROM APP_USER_ROLE ur
      JOIN APP_ROLE r ON r.ROLE_ID = ur.ROLE_ID
      WHERE ur.USER_ID = u.USER_ID
        AND r.ROLE_CODE IN ('MANAGER', 'SUPERVISOR')
  )
  AND NOT EXISTS (
      SELECT 1
      FROM APP_USER_ORGANIZATION uo
      JOIN ORGANIZATION o ON o.ORGANIZATION_ID = uo.ORGANIZATION_ID
      WHERE uo.USER_ID = u.USER_ID
        AND uo.STATUS = 'ACTIVE'
        AND o.ORGANIZATION_TYPE = 'CUSTOMER'
  );

