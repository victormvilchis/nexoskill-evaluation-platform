CREATE TABLE QUESTION_CATEGORY_STATUS_HISTORY (
    CATEGORY_STATUS_HISTORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY_ID NUMBER NOT NULL,
    ACTOR_USER_ID NUMBER,
    PREVIOUS_STATUS VARCHAR2(20 CHAR),
    NEW_STATUS VARCHAR2(20 CHAR) NOT NULL,
    REASON VARCHAR2(500 CHAR),
    OCCURRED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_QCATEGORY_STATUS_HISTORY PRIMARY KEY (CATEGORY_STATUS_HISTORY_ID),
    CONSTRAINT FK_QCSH_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES QUESTION_CATEGORY (CATEGORY_ID),
    CONSTRAINT FK_QCSH_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_QCSH_PREVIOUS CHECK (
        PREVIOUS_STATUS IS NULL OR PREVIOUS_STATUS IN ('ACTIVE', 'INACTIVE', 'DELETED')
    ),
    CONSTRAINT CK_QCSH_NEW CHECK (NEW_STATUS IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

CREATE INDEX IX_QCSH_CATEGORY_DATE
    ON QUESTION_CATEGORY_STATUS_HISTORY (CATEGORY_ID, OCCURRED_AT DESC);

