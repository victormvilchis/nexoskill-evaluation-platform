CREATE OR REPLACE TRIGGER TRG_ORG_LICENSE_CUSTOMER_ONLY
BEFORE INSERT OR UPDATE OF ORGANIZATION_ID ON ORGANIZATION_LICENSE_POLICY
FOR EACH ROW
DECLARE
    v_type ORGANIZATION.ORGANIZATION_TYPE%TYPE;
BEGIN
    IF :NEW.ORGANIZATION_ID IS NULL THEN
        RAISE_APPLICATION_ERROR(-20041, 'La política de licenciamiento requiere una organización comercial.');
    END IF;

    SELECT ORGANIZATION_TYPE
      INTO v_type
      FROM ORGANIZATION
     WHERE ORGANIZATION_ID = :NEW.ORGANIZATION_ID;

    IF v_type <> 'CUSTOMER' THEN
        RAISE_APPLICATION_ERROR(-20042, 'La organización global no utiliza políticas de licenciamiento.');
    END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE QUESTION_CATEGORY DROP CONSTRAINT CK_QUESTION_CATEGORY_STATUS';
