CREATE TABLE STUDENT (
    STUDENT_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID                 VARCHAR2(36 CHAR) NOT NULL,
    ORGANIZATION_ID           NUMBER NOT NULL,
    STUDENT_CODE              VARCHAR2(80 CHAR) NOT NULL,
    EMAIL                     VARCHAR2(254 CHAR) NOT NULL,
    NORMALIZED_EMAIL          VARCHAR2(254 CHAR) NOT NULL,
    PASSWORD_HASH             VARCHAR2(255 CHAR) NOT NULL,
    FIRST_NAME                VARCHAR2(100 CHAR) NOT NULL,
    LAST_NAME                 VARCHAR2(150 CHAR) NOT NULL,
    DISPLAY_NAME              VARCHAR2(250 CHAR) NOT NULL,
    STATUS                    VARCHAR2(30 CHAR) DEFAULT 'INACTIVE' NOT NULL,
    VALID_FROM                TIMESTAMP WITH TIME ZONE NOT NULL,
    EXPIRES_AT                TIMESTAMP WITH TIME ZONE,
    FAILED_LOGIN_ATTEMPTS     NUMBER DEFAULT 0 NOT NULL,
    LOCKED_UNTIL              TIMESTAMP WITH TIME ZONE,
    LAST_LOGIN_AT             TIMESTAMP WITH TIME ZONE,
    PASSWORD_CHANGED_AT       TIMESTAMP WITH TIME ZONE,
    PASSWORD_CHANGE_REQUIRED  NUMBER(1) DEFAULT 1 NOT NULL,
    TEMP_PASSWORD_EXPIRES_AT  TIMESTAMP WITH TIME ZONE,
    ARCHIVED_AT               TIMESTAMP WITH TIME ZONE,
    DELETED_AT                TIMESTAMP WITH TIME ZONE,
    DELETED_BY                NUMBER,
    DELETION_REASON           VARCHAR2(500 CHAR),
    CREATED_BY                NUMBER NOT NULL,
    UPDATED_BY                NUMBER,
    CREATED_AT                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION_NO                NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT PK_STUDENT PRIMARY KEY (STUDENT_ID),
    CONSTRAINT UK_STUDENT_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_STUDENT_ORG_CODE UNIQUE (ORGANIZATION_ID, STUDENT_CODE),
    CONSTRAINT UK_STUDENT_ORG_EMAIL UNIQUE (ORGANIZATION_ID, NORMALIZED_EMAIL),
    CONSTRAINT FK_STUDENT_ORGANIZATION FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT FK_STUDENT_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_STUDENT_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT FK_STUDENT_DELETED_BY FOREIGN KEY (DELETED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_STUDENT_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED','ARCHIVED','DELETED')),
    CONSTRAINT CK_STUDENT_PASSWORD_REQUIRED CHECK (PASSWORD_CHANGE_REQUIRED IN (0, 1)),
    CONSTRAINT CK_STUDENT_FAILED_ATTEMPTS CHECK (FAILED_LOGIN_ATTEMPTS >= 0),
    CONSTRAINT CK_STUDENT_DATES CHECK (EXPIRES_AT IS NULL OR EXPIRES_AT > VALID_FROM)
);

CREATE TABLE STUDENT_SESSION (
    STUDENT_SESSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID           VARCHAR2(36 CHAR) NOT NULL,
    STUDENT_ID          NUMBER NOT NULL,
    ORGANIZATION_ID     NUMBER NOT NULL,
    TOKEN_HASH          VARCHAR2(64 CHAR) NOT NULL,
    STATUS              VARCHAR2(30 CHAR) NOT NULL,
    IP_ADDRESS          VARCHAR2(64 CHAR),
    USER_AGENT          VARCHAR2(1000 CHAR),
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_ACTIVITY_AT    TIMESTAMP WITH TIME ZONE,
    EXPIRES_AT          TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED_AT          TIMESTAMP WITH TIME ZONE,
    REVOCATION_REASON   VARCHAR2(80 CHAR),
    VERSION_NO          NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT PK_STUDENT_SESSION PRIMARY KEY (STUDENT_SESSION_ID),
    CONSTRAINT UK_STUDENT_SESSION_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_STUDENT_SESSION_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_STUDENT_SESSION_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (STUDENT_ID),
    CONSTRAINT FK_STUDENT_SESSION_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT CK_STUDENT_SESSION_STATUS CHECK (STATUS IN ('ACTIVE','REVOKED','EXPIRED'))
);

CREATE INDEX IX_STUDENT_ORG_STATUS ON STUDENT (ORGANIZATION_ID, STATUS);
CREATE INDEX IX_STUDENT_ORG_NAME ON STUDENT (ORGANIZATION_ID, UPPER(DISPLAY_NAME));
CREATE INDEX IX_STUDENT_EXPIRATION ON STUDENT (EXPIRES_AT, STATUS);
CREATE INDEX IX_STUDENT_SESSION_STUDENT ON STUDENT_SESSION (STUDENT_ID, STATUS);
CREATE INDEX IX_STUDENT_SESSION_EXPIRATION ON STUDENT_SESSION (EXPIRES_AT, STATUS);

-- Oracle permite varios NULL. El índice funcional evita dos sesiones activas por estudiante.
CREATE UNIQUE INDEX UK_STUDENT_ONE_ACTIVE_SESSION
    ON STUDENT_SESSION (CASE WHEN STATUS = 'ACTIVE' THEN STUDENT_ID ELSE NULL END);
