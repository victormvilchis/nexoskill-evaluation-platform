-- Dashboard ejecutivo personalizable.
-- Reutiliza APP_PERMISSION/APP_ROLE_PERMISSION y persiste solo la composición visual por usuario.

MERGE INTO APP_PERMISSION target
USING (
    SELECT 'DASHBOARD_VIEW' code,
           'Consultar Dashboard' name,
           'DASHBOARD' module_code,
           'Permite visualizar el Dashboard y los indicadores correspondientes al alcance del usuario.' description
      FROM DUAL
    UNION ALL
    SELECT 'DASHBOARD_PERSONALIZE',
           'Personalizar Dashboard',
           'DASHBOARD',
           'Permite modificar la distribución, componentes y visualizaciones del Dashboard y guardar una configuración personal.'
      FROM DUAL
) source
ON (target.PERMISSION_CODE = source.code)
WHEN MATCHED THEN UPDATE SET
    target.PERMISSION_NAME = source.name,
    target.MODULE_CODE = source.module_code,
    target.DESCRIPTION = source.description
WHEN NOT MATCHED THEN INSERT (
    PERMISSION_CODE, PERMISSION_NAME, MODULE_CODE, DESCRIPTION
) VALUES (
    source.code, source.name, source.module_code, source.description
);

-- El Administrador global conserva acceso completo sin depender de una selección configurable.
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT role_value.ROLE_ID, permission_value.PERMISSION_ID
  FROM APP_ROLE role_value
 CROSS JOIN APP_PERMISSION permission_value
 WHERE role_value.ROLE_CODE = 'ADMINISTRATOR'
   AND permission_value.PERMISSION_CODE IN ('DASHBOARD_VIEW', 'DASHBOARD_PERSONALIZE')
   AND NOT EXISTS (
       SELECT 1
         FROM APP_ROLE_PERMISSION current_value
        WHERE current_value.ROLE_ID = role_value.ROLE_ID
          AND current_value.PERMISSION_ID = permission_value.PERMISSION_ID
   );

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'USER_DASHBOARD_PREFERENCE';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE USER_DASHBOARD_PREFERENCE (
                USER_DASHBOARD_PREFERENCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
                USER_ID NUMBER NOT NULL,
                CONFIGURATION_JSON CLOB NOT NULL,
                CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                VERSION_NO NUMBER DEFAULT 0 NOT NULL,
                CONSTRAINT PK_USER_DASHBOARD_PREF PRIMARY KEY (USER_DASHBOARD_PREFERENCE_ID),
                CONSTRAINT UK_USER_DASHBOARD_PREF_USER UNIQUE (USER_ID),
                CONSTRAINT FK_USER_DASHBOARD_PREF_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER (USER_ID),
                CONSTRAINT CK_USER_DASHBOARD_PREF_JSON CHECK (CONFIGURATION_JSON IS JSON),
                CONSTRAINT CK_USER_DASHBOARD_PREF_VERSION CHECK (VERSION_NO >= 0)
            )
        ]';
    ELSE
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'USER_DASHBOARD_PREFERENCE'
           AND COLUMN_NAME IN (
               'USER_DASHBOARD_PREFERENCE_ID', 'USER_ID', 'CONFIGURATION_JSON',
               'CREATED_AT', 'UPDATED_AT', 'VERSION_NO'
           );
        IF v_count <> 6 THEN
            RAISE_APPLICATION_ERROR(-20065,
                'USER_DASHBOARD_PREFERENCE existe parcialmente. Revisa sus columnas antes de reintentar V065.');
        END IF;
    END IF;
END;
/

COMMIT;
