DECLARE
    PROCEDURE create_table_if_missing(p_table VARCHAR2, p_sql CLOB) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = UPPER(p_table);
        IF v_count = 0 THEN EXECUTE IMMEDIATE p_sql; END IF;
    END;
