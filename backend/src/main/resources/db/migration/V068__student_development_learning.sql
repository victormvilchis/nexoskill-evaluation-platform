DECLARE
    FUNCTION index_with_columns(p_table VARCHAR2, p_columns VARCHAR2) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM (
                SELECT i.INDEX_NAME,
                       LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION) COLUMN_LIST
                  FROM USER_INDEXES i
                  JOIN USER_IND_COLUMNS c ON c.INDEX_NAME = i.INDEX_NAME
                 WHERE i.TABLE_NAME = UPPER(p_table)
                 GROUP BY i.INDEX_NAME
               )
         WHERE COLUMN_LIST = UPPER(p_columns);
        RETURN v_count;
    END;
BEGIN
    IF index_with_columns('STUDENT_PRACTICE_SESSION', 'ORGANIZATION_ID,STUDENT_ID,STATUS,STARTED_AT') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_PRACTICE_OWNER ON STUDENT_PRACTICE_SESSION (ORGANIZATION_ID, STUDENT_ID, STATUS, STARTED_AT)';
    END IF;
    IF index_with_columns('STUDENT_PRACTICE_QUESTION', 'PRACTICE_SESSION_ID,QUESTION_ORDER') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_PRACTICE_Q_SESSION ON STUDENT_PRACTICE_QUESTION (PRACTICE_SESSION_ID, QUESTION_ORDER)';
    END IF;
    IF index_with_columns('STUDENT_PRACTICE_ANSWER', 'SESSION_QUESTION_ID,ANSWERED_AT') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_PRACTICE_A_Q ON STUDENT_PRACTICE_ANSWER (SESSION_QUESTION_ID, ANSWERED_AT)';
    END IF;
    IF index_with_columns('STUDENT_FORM_ASSIGNMENT', 'ORGANIZATION_ID,STUDENT_ID,STATUS,ASSIGNED_AT') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_FORM_ASSIGN_OWNER ON STUDENT_FORM_ASSIGNMENT (ORGANIZATION_ID, STUDENT_ID, STATUS, ASSIGNED_AT)';
    END IF;
    IF index_with_columns('STUDENT_EVALUATION_ATTEMPT', 'ORGANIZATION_ID,STUDENT_ID,STATUS,STARTED_AT') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_EVALUATION_OWNER ON STUDENT_EVALUATION_ATTEMPT (ORGANIZATION_ID, STUDENT_ID, STATUS, STARTED_AT)';
    END IF;
    IF index_with_columns('STUDENT_EVALUATION_QUESTION', 'EVALUATION_ATTEMPT_ID,QUESTION_ORDER') = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STUDENT_EVALUATION_Q_ATT ON STUDENT_EVALUATION_QUESTION (EVALUATION_ATTEMPT_ID, QUESTION_ORDER)';
    END IF;
END;
