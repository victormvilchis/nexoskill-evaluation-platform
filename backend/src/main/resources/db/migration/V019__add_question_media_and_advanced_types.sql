CREATE TABLE QUESTION_MEDIA (
    MEDIA_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID            VARCHAR2(36 CHAR) NOT NULL,
    STORAGE_KEY          VARCHAR2(500 CHAR) NOT NULL,
    ORIGINAL_NAME        VARCHAR2(255 CHAR) NOT NULL,
    CONTENT_TYPE         VARCHAR2(100 CHAR) NOT NULL,
    FILE_SIZE            NUMBER NOT NULL,
    CHECKSUM_SHA256      VARCHAR2(64 CHAR) NOT NULL,
    CREATED_BY           NUMBER NOT NULL,
    CREATED_AT           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_QUESTION_MEDIA PRIMARY KEY (MEDIA_ID),
    CONSTRAINT UK_QUESTION_MEDIA_PUBLIC UNIQUE (PUBLIC_ID),
    CONSTRAINT UK_QUESTION_MEDIA_STORAGE UNIQUE (STORAGE_KEY),
    CONSTRAINT FK_QUESTION_MEDIA_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES APP_USER (USER_ID),
    CONSTRAINT CK_QUESTION_MEDIA_SIZE CHECK (FILE_SIZE > 0)
);

