-- Reutilización de decisiones para conflictos de importación exactamente equivalentes.
-- No almacena el archivo Excel ni justificaciones; conserva únicamente la firma funcional y la acción aplicada.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'STUDENT_IMPORT_CONFLICT_DECISION';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STUDENT_IMPORT_CONFLICT_DECISION (
                STUDENT_IMPORT_CONFLICT_DECISION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
                PUBLIC_ID VARCHAR2(36 CHAR) NOT NULL,
                ORGANIZATION_ID NUMBER NOT NULL,
                STUDENT_ID NUMBER NOT NULL,
                CERTIFICATION_TYPE VARCHAR2(40 CHAR) NOT NULL,
                CONFLICT_CODE VARCHAR2(80 CHAR) NOT NULL,
                CONFLICT_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
                ACTION_CODE VARCHAR2(20 CHAR) NOT NULL,
                CONSTRAINT PK_STU_IMP_CF_DEC PRIMARY KEY (STUDENT_IMPORT_CONFLICT_DECISION_ID),
                CONSTRAINT UK_STU_IMP_CF_PUBLIC UNIQUE (PUBLIC_ID),
                CONSTRAINT UK_STU_IMP_CF_EXACT UNIQUE (
                    ORGANIZATION_ID, STUDENT_ID, CERTIFICATION_TYPE,
                    CONFLICT_CODE, CONFLICT_FINGERPRINT
                ),
                CONSTRAINT FK_STU_IMP_CF_ORG FOREIGN KEY (ORGANIZATION_ID)
                    REFERENCES ORGANIZATION (ORGANIZATION_ID),
                CONSTRAINT FK_STU_IMP_CF_STUDENT FOREIGN KEY (STUDENT_ID)
                    REFERENCES STUDENT (STUDENT_ID),
                CONSTRAINT CK_STU_IMP_CF_TYPE CHECK (CERTIFICATION_TYPE IN (
                    'TECHNOLOGICAL', 'DEVELOPMENT_SECURITY', 'NORMATIVE_TESTING',
                    'ONE', 'AGILE', 'JIRA'
                )),
                CONSTRAINT CK_STU_IMP_CF_ACTION CHECK (ACTION_CODE IN (
                    'USE_PLATFORM', 'USE_EXCEL', 'OMIT_ROW'
                ))
            )
        ]';
    ELSE
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'STUDENT_IMPORT_CONFLICT_DECISION'
           AND COLUMN_NAME IN (
               'STUDENT_IMPORT_CONFLICT_DECISION_ID', 'PUBLIC_ID', 'ORGANIZATION_ID',
               'STUDENT_ID', 'CERTIFICATION_TYPE', 'CONFLICT_CODE',
               'CONFLICT_FINGERPRINT', 'ACTION_CODE'
           );
        IF v_count <> 8 THEN
            RAISE_APPLICATION_ERROR(-20050,
                'STUDENT_IMPORT_CONFLICT_DECISION existe parcialmente. Revisa sus columnas antes de reintentar V050.');
        END IF;
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM (
          SELECT i.INDEX_NAME,
                 LISTAGG(c.COLUMN_NAME, ',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION) COLUMN_LIST
            FROM USER_INDEXES i
            JOIN USER_IND_COLUMNS c ON c.INDEX_NAME = i.INDEX_NAME
           WHERE i.TABLE_NAME = 'STUDENT_IMPORT_CONFLICT_DECISION'
           GROUP BY i.INDEX_NAME
      )
     WHERE COLUMN_LIST = 'ORGANIZATION_ID,CONFLICT_CODE,STUDENT_ID';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_STU_IMP_CF_LOOKUP ON STUDENT_IMPORT_CONFLICT_DECISION (ORGANIZATION_ID, CONFLICT_CODE, STUDENT_ID)';
    END IF;
END;
