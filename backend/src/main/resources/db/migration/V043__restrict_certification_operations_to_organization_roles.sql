-- La gestión operativa de certificaciones corresponde únicamente a Gestores y Supervisores.
DELETE FROM APP_ROLE_PERMISSION rp
 WHERE rp.ROLE_ID IN (
       SELECT r.ROLE_ID FROM APP_ROLE r WHERE r.ROLE_CODE = 'ADMINISTRATOR'
   )
   AND rp.PERMISSION_ID IN (
       SELECT p.PERMISSION_ID FROM APP_PERMISSION p
        WHERE p.PERMISSION_CODE IN ('STUDENT_CERTIFICATION_MANAGE', 'STUDENT_CERTIFICATION_CATALOG_VIEW')
   );

INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ROLE_ID, p.PERMISSION_ID
  FROM APP_ROLE r
 CROSS JOIN APP_PERMISSION p
 WHERE r.ROLE_CODE IN ('MANAGER', 'SUPERVISOR')
   AND p.PERMISSION_CODE IN ('STUDENT_CERTIFICATION_MANAGE', 'STUDENT_CERTIFICATION_CATALOG_VIEW')
   AND NOT EXISTS (
       SELECT 1
         FROM APP_ROLE_PERMISSION rp
        WHERE rp.ROLE_ID = r.ROLE_ID
          AND rp.PERMISSION_ID = p.PERMISSION_ID
   );
