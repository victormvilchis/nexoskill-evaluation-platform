-- Simplifies the editorial workflow: every usable question is published immediately.
-- Previous published versions are archived when a newer current version exists.

UPDATE QUESTION_VERSION
SET VERSION_STATUS = 'ARCHIVED',
    STATUS_CHANGED_AT = COALESCE(STATUS_CHANGED_AT, SYSTIMESTAMP)
WHERE VERSION_STATUS = 'PUBLISHED'
  AND EXISTS (
      SELECT 1
      FROM QUESTION
      WHERE QUESTION.QUESTION_ID = QUESTION_VERSION.QUESTION_ID
        AND QUESTION.STATUS <> 'ARCHIVED'
        AND QUESTION.CURRENT_VERSION_ID <> QUESTION_VERSION.QUESTION_VERSION_ID
  );

UPDATE QUESTION_VERSION
SET VERSION_STATUS = 'PUBLISHED',
    STATUS_CHANGED_AT = COALESCE(STATUS_CHANGED_AT, SYSTIMESTAMP),
    PUBLISHED_AT = COALESCE(PUBLISHED_AT, SYSTIMESTAMP)
WHERE EXISTS (
    SELECT 1
    FROM QUESTION
    WHERE QUESTION.CURRENT_VERSION_ID = QUESTION_VERSION.QUESTION_VERSION_ID
      AND QUESTION.STATUS <> 'ARCHIVED'
);

UPDATE QUESTION
SET STATUS = 'PUBLISHED',
    PUBLISHED_VERSION_ID = CURRENT_VERSION_ID,
    UPDATED_AT = COALESCE(UPDATED_AT, SYSTIMESTAMP)
WHERE STATUS <> 'ARCHIVED';

UPDATE QUESTION_VERSION
SET VERSION_STATUS = 'ARCHIVED',
    STATUS_CHANGED_AT = COALESCE(STATUS_CHANGED_AT, SYSTIMESTAMP)
WHERE EXISTS (
    SELECT 1
    FROM QUESTION
    WHERE QUESTION.CURRENT_VERSION_ID = QUESTION_VERSION.QUESTION_VERSION_ID
      AND QUESTION.STATUS = 'ARCHIVED'
);

UPDATE QUESTION
SET PUBLISHED_VERSION_ID = NULL
WHERE STATUS = 'ARCHIVED';
