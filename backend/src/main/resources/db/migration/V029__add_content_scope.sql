DECLARE
    PROCEDURE add_scope(p_table VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = p_table;
        IF v_count = 0 THEN RETURN; END IF;
        SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = p_table AND COLUMN_NAME = 'CONTENT_SCOPE';
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (CONTENT_SCOPE VARCHAR2(20 CHAR) DEFAULT ''GLOBAL'' NOT NULL)';
        END IF;
        SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = p_table AND COLUMN_NAME = 'OWNER_ORGANIZATION_ID';
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (OWNER_ORGANIZATION_ID NUMBER)';
        END IF;
        SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = p_table AND COLUMN_NAME = 'SOURCE_GLOBAL_ID';
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (SOURCE_GLOBAL_ID NUMBER)';
        END IF;
        EXECUTE IMMEDIATE 'UPDATE ' || p_table || ' SET CONTENT_SCOPE = ''GLOBAL'' WHERE CONTENT_SCOPE IS NULL';
    END;
BEGIN
    add_scope('QUESTION');
    add_scope('QUESTION_CATEGORY');
    add_scope('EVALUATION_FORM');
    add_scope('LEARNING_COLLECTION');
END;
/

ALTER TABLE QUESTION ADD CONSTRAINT CK_QUESTION_SCOPE CHECK (
    (CONTENT_SCOPE = 'GLOBAL' AND OWNER_ORGANIZATION_ID IS NULL) OR
    (CONTENT_SCOPE = 'ORGANIZATION' AND OWNER_ORGANIZATION_ID IS NOT NULL)
);
ALTER TABLE QUESTION_CATEGORY ADD CONSTRAINT CK_QUESTION_CATEGORY_SCOPE CHECK (
    (CONTENT_SCOPE = 'GLOBAL' AND OWNER_ORGANIZATION_ID IS NULL) OR
    (CONTENT_SCOPE = 'ORGANIZATION' AND OWNER_ORGANIZATION_ID IS NOT NULL)
);
ALTER TABLE EVALUATION_FORM ADD CONSTRAINT CK_FORM_SCOPE CHECK (
    (CONTENT_SCOPE = 'GLOBAL' AND OWNER_ORGANIZATION_ID IS NULL) OR
    (CONTENT_SCOPE = 'ORGANIZATION' AND OWNER_ORGANIZATION_ID IS NOT NULL)
);
ALTER TABLE LEARNING_COLLECTION ADD CONSTRAINT CK_COLLECTION_SCOPE CHECK (
    (CONTENT_SCOPE = 'GLOBAL' AND OWNER_ORGANIZATION_ID IS NULL) OR
    (CONTENT_SCOPE = 'ORGANIZATION' AND OWNER_ORGANIZATION_ID IS NOT NULL)
);

ALTER TABLE QUESTION ADD CONSTRAINT FK_QUESTION_OWNER_ORG FOREIGN KEY (OWNER_ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID);
ALTER TABLE QUESTION_CATEGORY ADD CONSTRAINT FK_QCATEGORY_OWNER_ORG FOREIGN KEY (OWNER_ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID);
ALTER TABLE EVALUATION_FORM ADD CONSTRAINT FK_FORM_OWNER_ORG FOREIGN KEY (OWNER_ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID);
ALTER TABLE LEARNING_COLLECTION ADD CONSTRAINT FK_COLLECTION_OWNER_ORG FOREIGN KEY (OWNER_ORGANIZATION_ID) REFERENCES ORGANIZATION (ORGANIZATION_ID);

CREATE INDEX IX_QUESTION_TENANT ON QUESTION (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, STATUS);
CREATE INDEX IX_QCATEGORY_TENANT ON QUESTION_CATEGORY (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, STATUS);
CREATE INDEX IX_FORM_TENANT ON EVALUATION_FORM (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, STATUS);
CREATE INDEX IX_COLLECTION_TENANT ON LEARNING_COLLECTION (CONTENT_SCOPE, OWNER_ORGANIZATION_ID, STATUS);
